using System.Text;
using Microsoft.CodeAnalysis.CSharp;
using Parquet.SourceGenerator.Models;

namespace Parquet.SourceGenerator.Emitter.Components;

/// <summary>
/// Emits the storage shadows for a target's adapted members (docs/44-TYPE-ADAPTERS.md): one
/// internal property per member, typed as the adapter's surrogate, whose accessors are the only
/// place the conversion appears — as direct static calls, with null handled here rather than in
/// the adapter. Every other emitter sees an ordinary member of a type it already maps.
/// </summary>
internal static class AdapterShadowComponent
{
    /// <summary>Hint-name suffix of the shadow file, beside the serializer's own.</summary>
    public const string HintSuffix = "ParquetAdapters.g.cs";

    public static string EmitSource(AdapterShadowSet shadows)
    {
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated />");
        builder.AppendLine("#nullable enable");
        builder.AppendLine();

        if (!string.IsNullOrEmpty(shadows.Namespace))
        {
            builder.AppendLine($"namespace {shadows.Namespace};");
            builder.AppendLine();
        }

        string indent = string.Empty;
        foreach (string declaration in shadows.DeclarationChain)
        {
            builder.AppendLine($"{indent}{declaration}");
            builder.AppendLine($"{indent}{{");
            indent += "    ";
        }

        for (int i = 0; i < shadows.Members.Length; i++)
        {
            if (i > 0)
                builder.AppendLine();
            EmitShadow(builder, shadows.Members[i], indent);
        }

        for (int depth = shadows.DeclarationChain.Length - 1; depth >= 0; depth--)
        {
            builder.AppendLine($"{new string(' ', depth * 4)}}}");
        }

        return builder.ToString();
    }

    private static void EmitShadow(StringBuilder builder, AdapterShadowModel shadow, string indent)
    {
        string adapter = shadow.AdapterTypeName;
        string to = shadow.ToStorageMethod;
        string from = shadow.FromStorageMethod;
        string member = Identifier(shadow.MemberName);
        string setter = shadow.InitOnly ? "init" : "set";

        builder.AppendLine(
            $"{indent}/// <summary>Storage representation of <see cref=\"{member}\"/>, converted by <see cref=\"{adapter}\"/>. Generated for Parquet serialization; not part of the type's API.</summary>"
        );
        builder.AppendLine(
            $"{indent}[global::System.Diagnostics.DebuggerBrowsable(global::System.Diagnostics.DebuggerBrowsableState.Never)]"
        );
        builder.AppendLine(
            $"{indent}[global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]"
        );
        builder.AppendLine($"{indent}internal {shadow.ShadowTypeName} {shadow.ShadowName}");
        builder.AppendLine($"{indent}{{");

        if (shadow.IsNullable)
        {
            builder.AppendLine($"{indent}    get");
            builder.AppendLine($"{indent}    {{");
            builder.AppendLine(
                $"{indent}        if (this.{member} is {{ }} __value) return {adapter}.{to}(__value);"
            );
            builder.AppendLine($"{indent}        return null;");
            builder.AppendLine($"{indent}    }}");
            builder.AppendLine($"{indent}    {setter}");
            builder.AppendLine($"{indent}    {{");
            builder.AppendLine(
                $"{indent}        if (value is {{ }} __storage) this.{member} = {adapter}.{from}(__storage);"
            );
            builder.AppendLine($"{indent}        else this.{member} = null;");
            builder.AppendLine($"{indent}    }}");
        }
        else
        {
            builder.AppendLine($"{indent}    get => {adapter}.{to}(this.{member});");
            builder.AppendLine($"{indent}    {setter} => this.{member} = {adapter}.{from}(value);");
        }

        builder.AppendLine($"{indent}}}");
    }

    /// <summary>A member name as C# must spell it: reserved keywords need the verbatim prefix.</summary>
    private static string Identifier(string name) =>
        SyntaxFacts.GetKeywordKind(name) == SyntaxKind.None ? name : "@" + name;
}
