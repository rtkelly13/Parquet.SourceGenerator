using System;
using System.Text;
using Parquet.SourceGenerator.Models;

namespace Parquet.SourceGenerator.Emitter;

/// <summary>
/// Emits high-performance C# partial extension classes targeting Parquet.Net v6 low-level primitives.
/// Emits native 16-byte Guid binary encoding, static pre-allocated DataField members,
/// O(1) index-check schema field resolution, ArrayPool buffer recycling, and Native AOT compatibility.
/// </summary>
public static class CodeEmitter
{
    /// <summary>
    /// Generates complete C# source code string for a given target model.
    /// </summary>
    public static string EmitSource(TargetClassModel model)
    {
        var builder = new StringBuilder();

        builder.AppendLine("// <auto-generated />");
        builder.AppendLine("#nullable enable");
        builder.AppendLine("#pragma warning disable CS8600, CS8601, CS8602, CS8603, CS8604, CS8629");
        builder.AppendLine();

        if (!string.IsNullOrEmpty(model.Namespace))
        {
            builder.AppendLine($"namespace {model.Namespace};");
            builder.AppendLine();
        }

        string extensionsClassName = $"{model.ClassName}ParquetExtensions";

        builder.AppendLine($"public static partial class {extensionsClassName}");
        builder.AppendLine("{");

        EmitSchema(builder, model);
        builder.AppendLine();

        EmitStaticFields(builder, model);
        builder.AppendLine();

        // Streaming row group writer — low level primitives, 100M+ scale, Native AOT compatible
        EmitWriteRowGroupAsync(builder, model);
        builder.AppendLine();

        // Primary write API — async (v6 requires async for writer creation)
        EmitWriteAsync(builder, model);
        builder.AppendLine();

        // Batched streaming write — splits IEnumerable into fixed-size row groups
        EmitWriteBatchedAsync(builder, model);
        builder.AppendLine();

        // Read API — async (v6 low-level primitives)
        EmitReadAsync(builder, model);

        builder.AppendLine("}");

        return builder.ToString();
    }

    // ──────────────────────────────────────────────────────────
    //  SCHEMA & STATIC FIELD CACHING
    // ──────────────────────────────────────────────────────────

    private static void EmitSchema(StringBuilder builder, TargetClassModel model)
    {
        builder.AppendLine("    /// <summary>");
        builder.AppendLine($"    /// Static compile-time <see=\"global::Parquet.Schema.ParquetSchema\"/> for <see=\"{model.ClassName}\"/>.");
        builder.AppendLine("    /// </summary>");
        builder.AppendLine("    public static readonly global::Parquet.Schema.ParquetSchema Schema = new global::Parquet.Schema.ParquetSchema(");

        for (int i = 0; i < model.Properties.Length; i++)
        {
            PropertyModel prop = model.Properties[i];
            string comma = i < model.Properties.Length - 1 ? "," : "";
            builder.AppendLine($"        {GetFieldCreationExpression(prop)}{comma}");
        }

        builder.AppendLine("    );");
    }

    private static void EmitStaticFields(StringBuilder builder, TargetClassModel model)
    {
        for (int i = 0; i < model.Properties.Length; i++)
        {
            builder.AppendLine($"    private static readonly global::Parquet.Schema.DataField _field_{i} = (global::Parquet.Schema.DataField)Schema.Fields[{i}];");
        }
    }

    private static string GetFieldCreationExpression(PropertyModel prop)
    {
        string name = prop.ParquetColumnName;

        return prop.Kind switch
        {
            PropertyKind.Decimal when prop.DecimalPrecision.HasValue && prop.DecimalScale.HasValue =>
                $"new global::Parquet.Schema.DecimalDataField(\"{name}\", {prop.DecimalPrecision.Value}, {prop.DecimalScale.Value}, isNullable: {BoolLiteral(prop.IsNullable)})",

            PropertyKind.Decimal =>
                $"new global::Parquet.Schema.DecimalDataField(\"{name}\", 38, 18, isNullable: {BoolLiteral(prop.IsNullable)})",

            PropertyKind.DateTime =>
                $"new global::Parquet.Schema.DateTimeDataField(\"{name}\", global::Parquet.Schema.DateTimeFormat.Impala, isNullable: {BoolLiteral(prop.IsNullable)})",

            PropertyKind.TimeSpan =>
                $"new global::Parquet.Schema.TimeSpanDataField(\"{name}\", global::Parquet.Schema.TimeSpanFormat.MilliSeconds, isNullable: {BoolLiteral(prop.IsNullable)})",

            PropertyKind.Guid =>
                $"new global::Parquet.Schema.DataField(\"{name}\", typeof(global::System.Guid), isNullable: {BoolLiteral(prop.IsNullable)})",

            PropertyKind.Enum =>
                $"new global::Parquet.Schema.DataField(\"{name}\", typeof({prop.EnumUnderlyingTypeName ?? "int"}), isNullable: {BoolLiteral(prop.IsNullable)})",

            PropertyKind.ByteArray =>
                $"new global::Parquet.Schema.DataField(\"{name}\", typeof(byte[]), isNullable: {BoolLiteral(prop.IsNullable)})",

            _ =>
                $"new global::Parquet.Schema.DataField(\"{name}\", typeof({prop.TypeName.TrimEnd('?')}), isNullable: {BoolLiteral(prop.IsNullable)})",
        };
    }

    // ──────────────────────────────────────────────────────────
    //  WRITE ROW GROUP (Low-Level Primitives, Static Field Access)
    // ──────────────────────────────────────────────────────────

    private static void EmitWriteRowGroupAsync(StringBuilder builder, TargetClassModel model)
    {
        builder.AppendLine("    /// <summary>");
        builder.AppendLine($"    /// Writes a single row group chunk using Parquet.Net low-level primitives for maximum speed and Native AOT compatibility.");
        builder.AppendLine("    /// </summary>");
        builder.AppendLine($"    public static async global::System.Threading.Tasks.Task WriteParquetRowGroupAsync(");
        builder.AppendLine($"        this global::Parquet.ParquetWriter writer,");
        builder.AppendLine($"        global::System.Collections.Generic.IReadOnlyCollection<{model.ClassName}> chunk,");
        builder.AppendLine($"        global::System.Threading.CancellationToken cancellationToken = default)");
        builder.AppendLine("    {");
        builder.AppendLine("        if (writer == null) throw new global::System.ArgumentNullException(nameof(writer));");
        builder.AppendLine("        if (chunk == null) throw new global::System.ArgumentNullException(nameof(chunk));");
        builder.AppendLine();
        builder.AppendLine("        int count = chunk.Count;");
        builder.AppendLine("        if (count == 0) return;");
        builder.AppendLine();

        for (int i = 0; i < model.Properties.Length; i++)
        {
            PropertyModel prop = model.Properties[i];
            string bufType = GetBufferElementType(prop);
            builder.AppendLine($"        var buffer_{i} = global::System.Buffers.ArrayPool<{bufType}>.Shared.Rent(count);");
        }

        builder.AppendLine();
        builder.AppendLine("        try");
        builder.AppendLine("        {");

        // List fast path
        builder.AppendLine($"            if (chunk is global::System.Collections.Generic.List<{model.ClassName}> listItems)");
        builder.AppendLine("            {");
        builder.AppendLine("                for (int i = 0; i < count; i++)");
        builder.AppendLine("                {");
        builder.AppendLine($"                    var item = listItems[i];");
        EmitPropertyAssignments(builder, model, "buffer_", prefix: "                    ");
        builder.AppendLine("                }");
        builder.AppendLine("            }");

        // Array fast path
        builder.AppendLine($"            else if (chunk is {model.ClassName}[] arrayItems)");
        builder.AppendLine("            {");
        builder.AppendLine("                for (int i = 0; i < count; i++)");
        builder.AppendLine("                {");
        builder.AppendLine($"                    var item = arrayItems[i];");
        EmitPropertyAssignments(builder, model, "buffer_", prefix: "                    ");
        builder.AppendLine("                }");
        builder.AppendLine("            }");

        // Enumerable fallback
        builder.AppendLine("            else");
        builder.AppendLine("            {");
        builder.AppendLine("                int idx = 0;");
        builder.AppendLine("                foreach (var item in chunk)");
        builder.AppendLine("                {");
        EmitPropertyAssignmentsIndexed(builder, model, "buffer_", prefix: "                    ");
        builder.AppendLine("                    idx++;");
        builder.AppendLine("                }");
        builder.AppendLine("            }");
        builder.AppendLine();

        // Write row group using static pre-allocated DataFields
        builder.AppendLine("            using (var groupWriter = writer.CreateRowGroup())");
        builder.AppendLine("            {");

        for (int i = 0; i < model.Properties.Length; i++)
        {
            PropertyModel prop = model.Properties[i];
            string fieldAccess = $"_field_{i}";
            string writeCall = GetWritePrimitiveCall(prop, fieldAccess, $"buffer_{i}");
            builder.AppendLine($"                {writeCall}");
        }

        builder.AppendLine("            }");
        builder.AppendLine("        }");
        builder.AppendLine("        finally");
        builder.AppendLine("        {");

        for (int i = 0; i < model.Properties.Length; i++)
        {
            PropertyModel prop = model.Properties[i];
            string bufType = GetBufferElementType(prop);
            bool isRef = IsReferenceTypeBuffer(prop);
            string clearArg = isRef ? "clearArray: true" : "clearArray: false";
            builder.AppendLine($"            global::System.Buffers.ArrayPool<{bufType}>.Shared.Return(buffer_{i}, {clearArg});");
        }

        builder.AppendLine("        }");
        builder.AppendLine("    }");
    }

    // ──────────────────────────────────────────────────────────
    //  WRITE (full collection)
    // ──────────────────────────────────────────────────────────

    private static void EmitWriteAsync(StringBuilder builder, TargetClassModel model)
    {
        builder.AppendLine("    /// <summary>");
        builder.AppendLine($"    /// Asynchronously serializes all <see=\"{model.ClassName}\"/> items using Parquet.Net low-level primitives.");
        builder.AppendLine("    /// </summary>");
        builder.AppendLine($"    public static async global::System.Threading.Tasks.Task WriteParquetAsync(");
        builder.AppendLine($"        this global::System.Collections.Generic.IReadOnlyCollection<{model.ClassName}> items,");
        builder.AppendLine($"        global::System.IO.Stream stream,");
        builder.AppendLine($"        global::System.Threading.CancellationToken cancellationToken = default)");
        builder.AppendLine("    {");
        builder.AppendLine("        if (items == null) throw new global::System.ArgumentNullException(nameof(items));");
        builder.AppendLine("        if (stream == null) throw new global::System.ArgumentNullException(nameof(stream));");
        builder.AppendLine("        cancellationToken.ThrowIfCancellationRequested();");
        builder.AppendLine();
        builder.AppendLine("        await using var writer = await global::Parquet.ParquetWriter.CreateAsync(Schema, stream, cancellationToken: cancellationToken);");
        builder.AppendLine("        await writer.WriteParquetRowGroupAsync(items, cancellationToken);");
        builder.AppendLine("    }");
    }

    // ──────────────────────────────────────────────────────────
    //  WRITE BATCHED
    // ──────────────────────────────────────────────────────────

    private static void EmitWriteBatchedAsync(StringBuilder builder, TargetClassModel model)
    {
        builder.AppendLine("    /// <summary>");
        builder.AppendLine($"    /// Streams <see=\"{model.ClassName}\"/> items into a Parquet file in fixed-size row group batches using low-level primitives.");
        builder.AppendLine("    /// </summary>");
        builder.AppendLine($"    public static async global::System.Threading.Tasks.Task WriteParquetBatchedAsync(");
        builder.AppendLine($"        this global::System.Collections.Generic.IEnumerable<{model.ClassName}> items,");
        builder.AppendLine($"        global::System.IO.Stream stream,");
        builder.AppendLine($"        int rowGroupSize = 50_000,");
        builder.AppendLine($"        global::System.Threading.CancellationToken cancellationToken = default)");
        builder.AppendLine("    {");
        builder.AppendLine("        if (items == null) throw new global::System.ArgumentNullException(nameof(items));");
        builder.AppendLine("        if (stream == null) throw new global::System.ArgumentNullException(nameof(stream));");
        builder.AppendLine("        if (rowGroupSize <= 0) throw new global::System.ArgumentOutOfRangeException(nameof(rowGroupSize));");
        builder.AppendLine();
        builder.AppendLine("        await using var writer = await global::Parquet.ParquetWriter.CreateAsync(Schema, stream, cancellationToken: cancellationToken);");
        builder.AppendLine($"        var buffer = new global::System.Collections.Generic.List<{model.ClassName}>(rowGroupSize);");
        builder.AppendLine("        foreach (var item in items)");
        builder.AppendLine("        {");
        builder.AppendLine("            cancellationToken.ThrowIfCancellationRequested();");
        builder.AppendLine("            buffer.Add(item);");
        builder.AppendLine("            if (buffer.Count == rowGroupSize)");
        builder.AppendLine("            {");
        builder.AppendLine("                await writer.WriteParquetRowGroupAsync(buffer, cancellationToken);");
        builder.AppendLine("                buffer.Clear();");
        builder.AppendLine("            }");
        builder.AppendLine("        }");
        builder.AppendLine("        if (buffer.Count > 0)");
        builder.AppendLine("            await writer.WriteParquetRowGroupAsync(buffer, cancellationToken);");
        builder.AppendLine("    }");
    }

    // ──────────────────────────────────────────────────────────
    //  READ (Low-Level Primitives, Fast Static Field Resolution)
    // ──────────────────────────────────────────────────────────

    private static void EmitReadAsync(StringBuilder builder, TargetClassModel model)
    {
        builder.AppendLine("    /// <summary>");
        builder.AppendLine($"    /// Asynchronously deserializes all <see=\"{model.ClassName}\"/> objects using Parquet.Net low-level primitives.");
        builder.AppendLine("    /// Fast O(1) index-check schema resolution and ArrayPool buffer recycling.");
        builder.AppendLine("    /// </summary>");
        builder.AppendLine($"    public static async global::System.Threading.Tasks.Task<global::System.Collections.Generic.List<{model.ClassName}>> ReadParquetAsync(");
        builder.AppendLine($"        global::System.IO.Stream stream,");
        builder.AppendLine($"        global::System.Threading.CancellationToken cancellationToken = default)");
        builder.AppendLine("    {");
        builder.AppendLine("        if (stream == null) throw new global::System.ArgumentNullException(nameof(stream));");
        builder.AppendLine();
        builder.AppendLine($"        var results = new global::System.Collections.Generic.List<{model.ClassName}>();");
        builder.AppendLine("        await using var reader = await global::Parquet.ParquetReader.CreateAsync(stream, cancellationToken: cancellationToken);");
        builder.AppendLine();
        builder.AppendLine("        var fileFields = reader.Schema.DataFields;");

        // Fast O(1) schema field resolution using pre-allocated static DataFields
        for (int i = 0; i < model.Properties.Length; i++)
        {
            PropertyModel prop = model.Properties[i];
            builder.AppendLine($"        var field_{i} = ({i} < fileFields.Length && string.Equals(fileFields[{i}].Name, _field_{i}.Name, global::System.StringComparison.OrdinalIgnoreCase)) ? fileFields[{i}] : (fileFields.FirstOrDefault(f => string.Equals(f.Name, _field_{i}.Name, global::System.StringComparison.OrdinalIgnoreCase)) ?? _field_{i});");
        }
        builder.AppendLine();

        builder.AppendLine("        for (int r = 0; r < reader.RowGroupCount; r++)");
        builder.AppendLine("        {");
        builder.AppendLine("            cancellationToken.ThrowIfCancellationRequested();");
        builder.AppendLine("            using var groupReader = reader.OpenRowGroupReader(r);");
        builder.AppendLine("            int rowCount = (int)groupReader.RowCount;");
        builder.AppendLine();

        // Rent buffers for column reading
        for (int i = 0; i < model.Properties.Length; i++)
        {
            PropertyModel prop = model.Properties[i];
            string bufType = GetBufferElementType(prop);
            builder.AppendLine($"            var buffer_{i} = global::System.Buffers.ArrayPool<{bufType}>.Shared.Rent(rowCount);");
        }

        builder.AppendLine();
        builder.AppendLine("            try");
        builder.AppendLine("            {");

        // Read columns using low-level primitive ReadAsync
        for (int i = 0; i < model.Properties.Length; i++)
        {
            PropertyModel prop = model.Properties[i];
            string fieldAccess = $"field_{i}";
            string readCall = GetReadPrimitiveCall(prop, fieldAccess, $"buffer_{i}");
            builder.AppendLine($"                {readCall}");
        }

        builder.AppendLine();
        builder.AppendLine("                results.Capacity = results.Count + rowCount;");
        builder.AppendLine("                for (int i = 0; i < rowCount; i++)");
        builder.AppendLine("                {");
        builder.AppendLine($"                    results.Add(new {model.ClassName}");
        builder.AppendLine("                    {");

        for (int i = 0; i < model.Properties.Length; i++)
        {
            PropertyModel prop = model.Properties[i];
            string readExpr = GetReadExpression(prop, $"buffer_{i}[i]");
            builder.AppendLine($"                        {prop.Name} = {readExpr},");
        }

        builder.AppendLine("                    });");
        builder.AppendLine("                }");
        builder.AppendLine("            }");
        builder.AppendLine("            finally");
        builder.AppendLine("            {");

        for (int i = 0; i < model.Properties.Length; i++)
        {
            PropertyModel prop = model.Properties[i];
            string bufType = GetBufferElementType(prop);
            bool isRef = IsReferenceTypeBuffer(prop);
            string clearArg = isRef ? "clearArray: true" : "clearArray: false";
            builder.AppendLine($"                global::System.Buffers.ArrayPool<{bufType}>.Shared.Return(buffer_{i}, {clearArg});");
        }

        builder.AppendLine("            }");
        builder.AppendLine("        }");
        builder.AppendLine();
        builder.AppendLine("        return results;");
        builder.AppendLine("    }");
    }

    // ──────────────────────────────────────────────────────────
    //  HELPERS
    // ──────────────────────────────────────────────────────────

    private static void EmitPropertyAssignments(StringBuilder builder, TargetClassModel model, string bufPrefix, string prefix)
    {
        for (int i = 0; i < model.Properties.Length; i++)
        {
            PropertyModel prop = model.Properties[i];
            string writeExpr = GetWriteExpression(prop, $"item.{prop.Name}");
            builder.AppendLine($"{prefix}{bufPrefix}{i}[i] = {writeExpr};");
        }
    }

    private static void EmitPropertyAssignmentsIndexed(StringBuilder builder, TargetClassModel model, string bufPrefix, string prefix)
    {
        for (int i = 0; i < model.Properties.Length; i++)
        {
            PropertyModel prop = model.Properties[i];
            string writeExpr = GetWriteExpression(prop, $"item.{prop.Name}");
            builder.AppendLine($"{prefix}{bufPrefix}{i}[idx] = {writeExpr};");
        }
    }

    private static string GetBufferElementType(PropertyModel prop)
    {
        return prop.Kind switch
        {
            PropertyKind.Guid when prop.IsNullable => "global::System.Guid?",
            PropertyKind.Guid => "global::System.Guid",
            PropertyKind.Enum when prop.IsNullable => $"{prop.EnumUnderlyingTypeName ?? "int"}?",
            PropertyKind.Enum => prop.EnumUnderlyingTypeName ?? "int",
            _ => prop.TypeName,
        };
    }

    private static bool IsReferenceTypeBuffer(PropertyModel prop)
    {
        return prop.Kind switch
        {
            PropertyKind.Guid => false, // Guid is a 16-byte value type struct!
            PropertyKind.ByteArray => true,
            PropertyKind.Primitive when prop.TypeName.Contains("string") => true,
            _ => false,
        };
    }

    private static string GetWriteExpression(PropertyModel prop, string valueExpr)
    {
        return prop.Kind switch
        {
            PropertyKind.Guid => valueExpr, // Direct Guid value copy! Zero allocations!
            PropertyKind.Enum when prop.IsNullable => $"{valueExpr} is null ? ({prop.EnumUnderlyingTypeName ?? "int"}?)null : ({prop.EnumUnderlyingTypeName ?? "int"}){valueExpr}.Value",
            PropertyKind.Enum => $"({prop.EnumUnderlyingTypeName ?? "int"}){valueExpr}",
            _ => valueExpr,
        };
    }

    private static string GetReadExpression(PropertyModel prop, string valueExpr)
    {
        return prop.Kind switch
        {
            PropertyKind.Guid => valueExpr, // Direct Guid value read! Zero allocations!
            PropertyKind.Enum when prop.IsNullable =>
                $"{valueExpr} is null ? ({prop.TypeName})null : ({prop.TypeName.TrimEnd('?')}){valueExpr}!",
            PropertyKind.Enum =>
                $"({prop.TypeName.TrimEnd('?')}){valueExpr}",
            _ => valueExpr,
        };
    }

    private static string GetWritePrimitiveCall(PropertyModel prop, string fieldAccess, string bufName)
    {
        bool isString = prop.Kind == PropertyKind.Primitive && prop.TypeName.Contains("string");
        bool isByteArray = prop.Kind == PropertyKind.ByteArray;

        if (isString)
        {
            return $"await groupWriter.WriteAsync({fieldAccess}, new global::System.ArraySegment<string?>({bufName}, 0, count));";
        }
        else if (isByteArray)
        {
            return $"await groupWriter.WriteAsync({fieldAccess}, new global::System.ArraySegment<byte[]?>({bufName}, 0, count));";
        }
        else if (prop.Kind == PropertyKind.Guid)
        {
            if (prop.IsNullable)
                return $"await groupWriter.WriteAsync<global::System.Guid>({fieldAccess}, new global::System.ReadOnlyMemory<global::System.Guid?>({bufName}, 0, count), cancellationToken: cancellationToken);";
            else
                return $"await groupWriter.WriteAsync<global::System.Guid>({fieldAccess}, new global::System.ReadOnlyMemory<global::System.Guid>({bufName}, 0, count), cancellationToken: cancellationToken);";
        }
        else if (prop.Kind == PropertyKind.Enum)
        {
            string underlying = prop.EnumUnderlyingTypeName ?? "int";
            if (prop.IsNullable)
                return $"await groupWriter.WriteAsync<{underlying}>({fieldAccess}, new global::System.ReadOnlyMemory<{underlying}?>({bufName}, 0, count), cancellationToken: cancellationToken);";
            else
                return $"await groupWriter.WriteAsync<{underlying}>({fieldAccess}, new global::System.ReadOnlyMemory<{underlying}>({bufName}, 0, count), cancellationToken: cancellationToken);";
        }
        else
        {
            string structType = prop.TypeName.TrimEnd('?');
            if (prop.IsNullable)
                return $"await groupWriter.WriteAsync<{structType}>({fieldAccess}, new global::System.ReadOnlyMemory<{structType}?>({bufName}, 0, count), cancellationToken: cancellationToken);";
            else
                return $"await groupWriter.WriteAsync<{structType}>({fieldAccess}, new global::System.ReadOnlyMemory<{structType}>({bufName}, 0, count), cancellationToken: cancellationToken);";
        }
    }

    private static string GetReadPrimitiveCall(PropertyModel prop, string fieldAccess, string bufName)
    {
        bool isString = prop.Kind == PropertyKind.Primitive && prop.TypeName.Contains("string");
        bool isByteArray = prop.Kind == PropertyKind.ByteArray;

        if (isString)
        {
            return $"await groupReader.ReadAsync({fieldAccess}, new global::System.Memory<string?>({bufName}, 0, rowCount), cancellationToken: cancellationToken);";
        }
        else if (isByteArray)
        {
            return $"await groupReader.ReadAsync({fieldAccess}, new global::System.Memory<byte[]?>({bufName}, 0, rowCount), cancellationToken: cancellationToken);";
        }
        else if (prop.Kind == PropertyKind.Guid)
        {
            if (prop.IsNullable)
                return $"await groupReader.ReadAsync<global::System.Guid>({fieldAccess}, new global::System.Memory<global::System.Guid?>({bufName}, 0, rowCount), cancellationToken: cancellationToken);";
            else
                return $"await groupReader.ReadAsync<global::System.Guid>({fieldAccess}, new global::System.Memory<global::System.Guid>({bufName}, 0, rowCount), cancellationToken: cancellationToken);";
        }
        else if (prop.Kind == PropertyKind.Enum)
        {
            string underlying = prop.EnumUnderlyingTypeName ?? "int";
            if (prop.IsNullable)
                return $"await groupReader.ReadAsync<{underlying}>({fieldAccess}, new global::System.Memory<{underlying}?>({bufName}, 0, rowCount), cancellationToken: cancellationToken);";
            else
                return $"await groupReader.ReadAsync<{underlying}>({fieldAccess}, new global::System.Memory<{underlying}>({bufName}, 0, rowCount), cancellationToken: cancellationToken);";
        }
        else
        {
            string structType = prop.TypeName.TrimEnd('?');
            if (prop.IsNullable)
                return $"await groupReader.ReadAsync<{structType}>({fieldAccess}, new global::System.Memory<{structType}?>({bufName}, 0, rowCount), cancellationToken: cancellationToken);";
            else
                return $"await groupReader.ReadAsync<{structType}>({fieldAccess}, new global::System.Memory<{structType}>({bufName}, 0, rowCount), cancellationToken: cancellationToken);";
        }
    }

    private static string BoolLiteral(bool value) => value ? "true" : "false";
}
