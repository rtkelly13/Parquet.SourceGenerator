    private static void EmitBuildFormatOptions(StringBuilder builder, TargetClassModel model)
    {
        builder.AppendLine("    /// <summary>");
        builder.AppendLine(
            "    /// Translates the generator's options into the Parquet.Net options the writer accepts."
        );
        builder.AppendLine("    /// </summary>");
        builder.AppendLine(
            "    private static global::Parquet.ParquetOptions BuildFormatOptions(global::Parquet.SourceGenerator.ParquetSerializerOptions options)"
        );
        builder.AppendLine("    {");
        builder.AppendLine("        var formatOptions = new global::Parquet.ParquetOptions");
        builder.AppendLine("        {");
        builder.AppendLine("            CompressionMethod = options.CompressionMethod switch");
        builder.AppendLine("            {");
        builder.AppendLine(
            "                global::Parquet.SourceGenerator.ParquetCompressionMethod.None =>"
        );
        builder.AppendLine("                    global::Parquet.CompressionMethod.None,");
        builder.AppendLine(
            "                global::Parquet.SourceGenerator.ParquetCompressionMethod.Gzip =>"
        );
        builder.AppendLine("                    global::Parquet.CompressionMethod.Gzip,");
        builder.AppendLine("                // Parquet.Net spells this one in caps.");
        builder.AppendLine(
            "                global::Parquet.SourceGenerator.ParquetCompressionMethod.Lz4 =>"
        );
        builder.AppendLine("                    global::Parquet.CompressionMethod.LZ4,");
        builder.AppendLine(
            "                global::Parquet.SourceGenerator.ParquetCompressionMethod.Brotli =>"
        );
        builder.AppendLine("                    global::Parquet.CompressionMethod.Brotli,");
        builder.AppendLine(
            "                global::Parquet.SourceGenerator.ParquetCompressionMethod.Zstd =>"
        );
        builder.AppendLine("                    global::Parquet.CompressionMethod.Zstd,");
        builder.AppendLine("                _ => global::Parquet.CompressionMethod.Snappy,");
        builder.AppendLine("            },");
        builder.AppendLine("        };");
        builder.AppendLine();
        builder.AppendLine("        if (options.CompressionLevel.HasValue)");
        builder.AppendLine("        {");
        builder.AppendLine(
            "            formatOptions.CompressionLevel = options.CompressionLevel.Value switch"
        );
        builder.AppendLine("            {");
        builder.AppendLine(
            "                global::Parquet.SourceGenerator.ParquetCompressionLevel.Optimal =>"
        );
        builder.AppendLine(
            "                    global::System.IO.Compression.CompressionLevel.Optimal,"
        );
        builder.AppendLine(
            "                global::Parquet.SourceGenerator.ParquetCompressionLevel.Fastest =>"
        );
        builder.AppendLine(
            "                    global::System.IO.Compression.CompressionLevel.Fastest,"
        );
        builder.AppendLine(
            "                global::Parquet.SourceGenerator.ParquetCompressionLevel.NoCompression =>"
        );
        builder.AppendLine(
            "                    global::System.IO.Compression.CompressionLevel.NoCompression,"
        );
        builder.AppendLine(
            "                _ => global::System.IO.Compression.CompressionLevel.SmallestSize,"
        );
        builder.AppendLine("            };");
        builder.AppendLine("        }");
        builder.AppendLine();
        builder.AppendLine("        if (options.DictionaryEncodingThreshold.HasValue)");
        builder.AppendLine("        {");
        builder.AppendLine(
            "            formatOptions.DictionaryEncodingThreshold = options.DictionaryEncodingThreshold.Value;"
        );
        builder.AppendLine("        }");
        builder.AppendLine();
        builder.AppendLine("        if (options.DictionaryEncodingSampleSize.HasValue)");
        builder.AppendLine("        {");
        builder.AppendLine(
            "            formatOptions.DictionaryEncodingSampleSize = options.DictionaryEncodingSampleSize.Value;"
        );
        builder.AppendLine("        }");

        foreach (var prop in model.Properties)
        {
            if (prop.Encoding != ColumnEncoding.Default)
            {
                string hintValue = prop.Encoding switch
                {
                    ColumnEncoding.Dictionary => "global::Parquet.EncodingHint.Dictionary",
                    ColumnEncoding.DeltaBinaryPacked =>
                        "global::Parquet.EncodingHint.DeltaBinaryPacked",
                    ColumnEncoding.ByteSplitStream =>
                        "global::Parquet.EncodingHint.ByteSplitStream",
                    _ => "global::Parquet.EncodingHint.Default",
                };
                builder.AppendLine(
                    $"        formatOptions.ColumnEncodingHints[\"{prop.ParquetColumnName}\"] = {hintValue};"
                );
            }
        }

        builder.AppendLine();
        builder.AppendLine("        foreach (var kvp in options.ColumnEncodingHints)");
        builder.AppendLine("        {");
        builder.AppendLine(
            "            formatOptions.ColumnEncodingHints[kvp.Key] = kvp.Value switch"
        );
        builder.AppendLine("            {");
        builder.AppendLine(
            "                global::Parquet.SourceGenerator.ParquetColumnEncoding.Dictionary =>"
        );
        builder.AppendLine("                    global::Parquet.EncodingHint.Dictionary,");
        builder.AppendLine(
            "                global::Parquet.SourceGenerator.ParquetColumnEncoding.DeltaBinaryPacked =>"
        );
        builder.AppendLine("                    global::Parquet.EncodingHint.DeltaBinaryPacked,");
        builder.AppendLine(
            "                global::Parquet.SourceGenerator.ParquetColumnEncoding.ByteSplitStream =>"
        );
        builder.AppendLine("                    global::Parquet.EncodingHint.ByteSplitStream,");
        builder.AppendLine("                _ => global::Parquet.EncodingHint.Default,");
        builder.AppendLine("            };");
        builder.AppendLine("        }");
        builder.AppendLine();
        builder.AppendLine("        return formatOptions;");
        builder.AppendLine("    }");
    }

    private static string GetWritePrimitiveCall(
        PropertyModel prop,
        string fieldAccess,
        string bufName,
        int propIndex,
        string indent = "                "
    )
    {
        bool isString = prop.Kind == PropertyKind.Primitive && prop.TypeName.Contains("string");
        bool isByteArray = prop.Kind == PropertyKind.ByteArray;

        if (BufferPoolComponent.UsesWriteAllParts(prop))
        {
            string nonNullType = BufferPoolComponent.GetNonNullableBufferType(prop);
            return $"{indent}await groupWriter.WriteAllPartsAsync<{nonNullType}>(\n"
                + $"{indent}    {fieldAccess},\n"
                + $"{indent}    new global::System.ReadOnlyMemory<{nonNullType}>({bufName}, 0, nonNullCount_{propIndex}),\n"
                + $"{indent}    new global::System.ReadOnlyMemory<int>(defLevels_{propIndex}, 0, count),\n"
                + $"{indent}    null,\n"
                + $"{indent}    cancellationToken: cancellationToken);";
        }
        else if (isString)
        {
            string memType = prop.IsNullable
                ? "global::System.ReadOnlyMemory<char>?"
                : "global::System.ReadOnlyMemory<char>";
            return $"{indent}await groupWriter.WriteAsync<global::System.ReadOnlyMemory<char>>(\n{indent}    {fieldAccess},\n{indent}    new global::System.ReadOnlyMemory<{memType}>({bufName}, 0, count),\n{indent}    cancellationToken: cancellationToken);";
        }
        else if (isByteArray)
        {
            string memType = prop.IsNullable
                ? "global::System.ReadOnlyMemory<byte>?"
                : "global::System.ReadOnlyMemory<byte>";
            return $"{indent}await groupWriter.WriteAsync<global::System.ReadOnlyMemory<byte>>(\n{indent}    {fieldAccess},\n{indent}    new global::System.ReadOnlyMemory<{memType}>({bufName}, 0, count),\n{indent}    cancellationToken: cancellationToken);";
        }
        else if (prop.Kind == PropertyKind.Guid)
        {
            return $"{indent}await groupWriter.WriteAsync<global::System.Guid>(\n{indent}    {fieldAccess},\n{indent}    new global::System.ReadOnlyMemory<global::System.Guid>({bufName}, 0, count),\n{indent}    cancellationToken: cancellationToken);";
        }
        else if (prop.Kind == PropertyKind.Enum)
        {
            string underlying = prop.EnumUnderlyingTypeName ?? "int";
            return $"{indent}await groupWriter.WriteAsync<{underlying}>(\n{indent}    {fieldAccess},\n{indent}    new global::System.ReadOnlyMemory<{underlying}>({bufName}, 0, count),\n{indent}    cancellationToken: cancellationToken);";
        }
        else if (prop.Kind == PropertyKind.TimeSpan)
        {
            return $"{indent}await groupWriter.WriteAsync<int>(\n{indent}    {fieldAccess},\n{indent}    new global::System.ReadOnlyMemory<int>({bufName}, 0, count),\n{indent}    cancellationToken: cancellationToken);";
        }
        else if (prop.Kind == PropertyKind.TimeSpan)
        {
            string memType = prop.IsNullable ? "int?" : "int";
            return $"{indent}await groupWriter.WriteAsync<int>(\n{indent}    {fieldAccess},\n{indent}    new global::System.ReadOnlyMemory<{memType}>({bufName}, 0, count),\n{indent}    cancellationToken: cancellationToken);";
        }
        else if (prop.Kind == PropertyKind.TimeOnly)
        {
            string memType = prop.IsNullable ? "long?" : "long";
            return $"{indent}await groupWriter.WriteAsync<long>(\n{indent}    {fieldAccess},\n{indent}    new global::System.ReadOnlyMemory<{memType}>({bufName}, 0, count),\n{indent}    cancellationToken: cancellationToken);";
        }
        else
        {
            string structType = prop.TypeName.TrimEnd('?');
            return $"{indent}await groupWriter.WriteAsync<{structType}>(\n{indent}    {fieldAccess},\n{indent}    new global::System.ReadOnlyMemory<{structType}>({bufName}, 0, count),\n{indent}    cancellationToken: cancellationToken);";
        }
    }

    private static string GetReadPrimitiveCall(
        PropertyModel prop,
        string fieldAccess,
        string bufName,
        string indent = "                "
    )
    {
        bool isString = prop.Kind == PropertyKind.Primitive && prop.TypeName.Contains("string");
        bool isByteArray = prop.Kind == PropertyKind.ByteArray;

        if (isString)
        {
            return $"{indent}await groupReader.ReadAsync(\n{indent}    {fieldAccess},\n{indent}    new global::System.Memory<string?>({bufName}, 0, rowCount),\n{indent}    cancellationToken: cancellationToken);";
        }
        else if (isByteArray)
        {
            return $"{indent}await groupReader.ReadAsync(\n{indent}    {fieldAccess},\n{indent}    new global::System.Memory<byte[]?>({bufName}, 0, rowCount),\n{indent}    cancellationToken: cancellationToken);";
        }
        else if (prop.Kind == PropertyKind.Guid)
        {
            string memType = prop.IsNullable ? "global::System.Guid?" : "global::System.Guid";
            return $"{indent}await groupReader.ReadAsync<global::System.Guid>(\n{indent}    {fieldAccess},\n{indent}    new global::System.Memory<{memType}>({bufName}, 0, rowCount),\n{indent}    cancellationToken: cancellationToken);";
        }
        else if (prop.Kind == PropertyKind.Enum)
        {
            string underlying = prop.EnumUnderlyingTypeName ?? "int";
            string memType = prop.IsNullable ? $"{underlying}?" : underlying;
            return $"{indent}await groupReader.ReadAsync<{underlying}>(\n{indent}    {fieldAccess},\n{indent}    new global::System.Memory<{memType}>({bufName}, 0, rowCount),\n{indent}    cancellationToken: cancellationToken);";
        }
        else if (prop.Kind == PropertyKind.TimeSpan)
        {
            string memType = prop.IsNullable ? "int?" : "int";
            return $"{indent}await groupReader.ReadAsync<int>(\n{indent}    {fieldAccess},\n{indent}    new global::System.Memory<{memType}>({bufName}, 0, rowCount),\n{indent}    cancellationToken: cancellationToken);";
        }
        else if (prop.Kind == PropertyKind.TimeOnly)
        {
            string memType = prop.IsNullable ? "long?" : "long";
            return $"{indent}await groupReader.ReadAsync<long>(\n{indent}    {fieldAccess},\n{indent}    new global::System.Memory<{memType}>({bufName}, 0, rowCount),\n{indent}    cancellationToken: cancellationToken);";
        }
        else
        {
            string structType = prop.TypeName.TrimEnd('?');
            string memType = prop.IsNullable ? $"{structType}?" : structType;
            return $"{indent}await groupReader.ReadAsync<{structType}>(\n{indent}    {fieldAccess},\n{indent}    new global::System.Memory<{memType}>({bufName}, 0, rowCount),\n{indent}    cancellationToken: cancellationToken);";
        }
    }

