    // ──────────────────────────────────────────────────────────
    //  READ (Sequential with options)
    // ──────────────────────────────────────────────────────────

    private static void EmitReadAsync(StringBuilder builder, TargetClassModel model)
    {
        builder.AppendLine("    /// <summary>");
        builder.AppendLine($"    /// Asynchronously deserializes all <c>{model.ClassName}</c> objects using Parquet.Net low-level primitives.");
        builder.AppendLine("    /// Fast O(1) index-check schema resolution and ArrayPool buffer recycling.");
        builder.AppendLine("    /// </summary>");
        builder.AppendLine($"    public static async global::System.Threading.Tasks.Task<global::System.Collections.Generic.List<{model.ClassName}>> ReadParquetAsync(");
        builder.AppendLine($"        global::System.IO.Stream stream,");
        builder.AppendLine($"        global::Parquet.SourceGenerator.ParquetSerializerOptions? options = null,");
        builder.AppendLine($"        global::System.Threading.CancellationToken cancellationToken = default)");
        builder.AppendLine("    {");
        builder.AppendLine("        if (stream == null) throw new global::System.ArgumentNullException(nameof(stream));");
        builder.AppendLine();
        builder.AppendLine("        options ??= global::Parquet.SourceGenerator.ParquetSerializerOptions.Default;");
        builder.AppendLine();
        builder.AppendLine($"        var results = new global::System.Collections.Generic.List<{model.ClassName}>();");
        builder.AppendLine("        await using var reader = await global::Parquet.ParquetReader.CreateAsync(stream, cancellationToken: cancellationToken);");
        builder.AppendLine();
        builder.AppendLine("        var fileFields = reader.Schema.DataFields;");

        // Schema field resolution against the file's actual fields (see ResolveSchemaField).
        if (model.Properties.Length > 0)
        {
            builder.AppendLine("        global::System.Collections.Generic.Dictionary<string, global::Parquet.Schema.DataField>? fieldsByName = null;");
            for (int i = 0; i < model.Properties.Length; i++)
            {
                builder.AppendLine($"        var field_{i} = ResolveSchemaField(fileFields, {i}, _field_{i}, ref fieldsByName);");
            }
        }
        builder.AppendLine();

        builder.AppendLine("        for (int r = 0; r < reader.RowGroupCount; r++)");
        builder.AppendLine("        {");
        builder.AppendLine("            cancellationToken.ThrowIfCancellationRequested();");
        builder.AppendLine("            using var groupReader = reader.OpenRowGroupReader(r);");
        builder.AppendLine("            int rowCount = (int)groupReader.RowCount;");
        builder.AppendLine();

        // Rent buffers for column reading
        for (int i = 0; i < model.Properties.Length; i++)
        {
            PropertyModel prop = model.Properties[i];
            string bufType = GetBufferElementType(prop);
            builder.AppendLine($"            var buffer_{i} = global::System.Buffers.ArrayPool<{bufType}>.Shared.Rent(rowCount);");
        }

        builder.AppendLine();
        builder.AppendLine("            try");
        builder.AppendLine("            {");

        // Read columns using low-level primitive ReadAsync
        for (int i = 0; i < model.Properties.Length; i++)
        {
            PropertyModel prop = model.Properties[i];
            string fieldAccess = $"field_{i}";
            string readCall = GetReadPrimitiveCall(prop, fieldAccess, $"buffer_{i}");
            builder.AppendLine($"                {readCall}");
        }

        builder.AppendLine();
        builder.AppendLine("                results.Capacity = results.Count + rowCount;");
        builder.AppendLine("                for (int i = 0; i < rowCount; i++)");
        builder.AppendLine("                {");
        builder.AppendLine($"                    results.Add(new {model.ClassName}");
        builder.AppendLine("                    {");

        for (int i = 0; i < model.Properties.Length; i++)
        {
            PropertyModel prop = model.Properties[i];
            string readExpr = GetReadExpression(prop, $"buffer_{i}[i]");
            builder.AppendLine($"                        {prop.Name} = {readExpr},");
        }

        builder.AppendLine("                    });");
        builder.AppendLine("                }");
        builder.AppendLine("            }");
        builder.AppendLine("            finally");
        builder.AppendLine("            {");

        for (int i = 0; i < model.Properties.Length; i++)
        {
            PropertyModel prop = model.Properties[i];
            string bufType = GetBufferElementType(prop);
            bool isRef = IsReferenceTypeBuffer(prop);
            string clearArg = isRef ? "clearArray: true" : "clearArray: false";
            builder.AppendLine($"                global::System.Buffers.ArrayPool<{bufType}>.Shared.Return(buffer_{i}, {clearArg});");
        }

        builder.AppendLine("            }");
        builder.AppendLine("        }");
        builder.AppendLine();
        builder.AppendLine("        return results;");
        builder.AppendLine("    }");
    }

    // ──────────────────────────────────────────────────────────
    //  READ PARALLEL (Multi-Core with options)
    // ──────────────────────────────────────────────────────────

    private static void EmitReadParallelAsync(StringBuilder builder, TargetClassModel model)
    {
        builder.AppendLine("    /// <summary>");
        builder.AppendLine($"    /// Asynchronously deserializes all <c>{model.ClassName}</c> objects from a Parquet stream using parallel worker tasks for multi-row-group files.");
        builder.AppendLine("    /// </summary>");
        builder.AppendLine($"    public static async global::System.Threading.Tasks.Task<global::System.Collections.Generic.List<{model.ClassName}>> ReadParquetParallelAsync(");
        builder.AppendLine($"        global::System.IO.Stream stream,");
        builder.AppendLine($"        int maxDegreeOfParallelism = -1,");
        builder.AppendLine($"        global::Parquet.SourceGenerator.ParquetSerializerOptions? options = null,");
        builder.AppendLine($"        global::System.Threading.CancellationToken cancellationToken = default)");
        builder.AppendLine("    {");
        builder.AppendLine("        if (stream == null) throw new global::System.ArgumentNullException(nameof(stream));");
        builder.AppendLine();
        builder.AppendLine("        options ??= global::Parquet.SourceGenerator.ParquetSerializerOptions.Default;");
        builder.AppendLine("        int targetParallelism = options.MaxDegreeOfParallelism > 0 ? options.MaxDegreeOfParallelism : maxDegreeOfParallelism;");
        builder.AppendLine();
        builder.AppendLine("        await using var reader = await global::Parquet.ParquetReader.CreateAsync(stream, cancellationToken: cancellationToken);");
        builder.AppendLine("        int rgCount = reader.RowGroupCount;");
        builder.AppendLine($"        if (rgCount == 0) return new global::System.Collections.Generic.List<{model.ClassName}>();");
        builder.AppendLine();
        builder.AppendLine("        var fileFields = reader.Schema.DataFields;");

        if (model.Properties.Length > 0)
        {
            builder.AppendLine("        global::System.Collections.Generic.Dictionary<string, global::Parquet.Schema.DataField>? fieldsByName = null;");
            for (int i = 0; i < model.Properties.Length; i++)
            {
                builder.AppendLine($"        var field_{i} = ResolveSchemaField(fileFields, {i}, _field_{i}, ref fieldsByName);");
            }
        }
        builder.AppendLine();

        builder.AppendLine($"        var partitions = new global::System.Collections.Generic.List<{model.ClassName}>[rgCount];");
        builder.AppendLine("        var parallelOpts = new global::System.Threading.Tasks.ParallelOptions");
        builder.AppendLine("        {");
        builder.AppendLine("            CancellationToken = cancellationToken,");
        builder.AppendLine("            MaxDegreeOfParallelism = targetParallelism <= 0 ? global::System.Environment.ProcessorCount : targetParallelism");
        builder.AppendLine("        };");
        builder.AppendLine();

        builder.AppendLine("        for (int r = 0; r < rgCount; r++)");
        builder.AppendLine("        {");
        builder.AppendLine("            cancellationToken.ThrowIfCancellationRequested();");
        builder.AppendLine("            using var groupReader = reader.OpenRowGroupReader(r);");
        builder.AppendLine("            int rowCount = (int)groupReader.RowCount;");
        builder.AppendLine();

        for (int i = 0; i < model.Properties.Length; i++)
        {
            PropertyModel prop = model.Properties[i];
            string bufType = GetBufferElementType(prop);
            builder.AppendLine($"            var buffer_{i} = global::System.Buffers.ArrayPool<{bufType}>.Shared.Rent(rowCount);");
        }

        builder.AppendLine();
        builder.AppendLine("            try");
        builder.AppendLine("            {");

        for (int i = 0; i < model.Properties.Length; i++)
        {
            PropertyModel prop = model.Properties[i];
            string fieldAccess = $"field_{i}";
            string readCall = GetReadPrimitiveCall(prop, fieldAccess, $"buffer_{i}");
            builder.AppendLine($"                {readCall}");
        }

        builder.AppendLine();
        builder.AppendLine($"                var groupItems = new {model.ClassName}[rowCount];");
        builder.AppendLine("                global::System.Threading.Tasks.Parallel.For(0, rowCount, parallelOpts, i =>");
        builder.AppendLine("                {");
        builder.AppendLine($"                    groupItems[i] = new {model.ClassName}");
        builder.AppendLine("                    {");

        for (int i = 0; i < model.Properties.Length; i++)
        {
            PropertyModel prop = model.Properties[i];
            string readExpr = GetReadExpression(prop, $"buffer_{i}[i]");
            builder.AppendLine($"                        {prop.Name} = {readExpr},");
        }

        builder.AppendLine("                    };");
        builder.AppendLine("                });");
        builder.AppendLine();
        builder.AppendLine($"                partitions[r] = new global::System.Collections.Generic.List<{model.ClassName}>(groupItems);");
        builder.AppendLine("            }");
        builder.AppendLine("            finally");
        builder.AppendLine("            {");

        for (int i = 0; i < model.Properties.Length; i++)
        {
            PropertyModel prop = model.Properties[i];
            string bufType = GetBufferElementType(prop);
            bool isRef = IsReferenceTypeBuffer(prop);
            string clearArg = isRef ? "clearArray: true" : "clearArray: false";
            builder.AppendLine($"                global::System.Buffers.ArrayPool<{bufType}>.Shared.Return(buffer_{i}, {clearArg});");
        }

        builder.AppendLine("            }");
        builder.AppendLine("        }");
        builder.AppendLine();
        builder.AppendLine($"        var totalList = new global::System.Collections.Generic.List<{model.ClassName}>();");
        builder.AppendLine("        for (int r = 0; r < rgCount; r++)");
        builder.AppendLine("        {");
        builder.AppendLine("            if (partitions[r] != null) totalList.AddRange(partitions[r]);");
        builder.AppendLine("        }");
        builder.AppendLine("        return totalList;");
        builder.AppendLine("    }");
    }

