    private static void EmitResolveSchemaField(StringBuilder builder)
    {
        builder.AppendLine("    /// <summary>");
        builder.AppendLine("    /// Resolves one generated schema field against the fields actually present in the file.");
        builder.AppendLine("    /// </summary>");
        builder.AppendLine("    private static global::Parquet.Schema.DataField ResolveSchemaField(");
        builder.AppendLine("        global::Parquet.Schema.DataField[] fileFields,");
        builder.AppendLine("        int index,");
        builder.AppendLine("        global::Parquet.Schema.DataField expected,");
        builder.AppendLine("        ref global::System.Collections.Generic.Dictionary<string, global::Parquet.Schema.DataField>? byName)");
        builder.AppendLine("    {");
        builder.AppendLine("        // Ordered schemas resolve on a single index check: no hashing, no delegate, no allocation.");
        builder.AppendLine("        // Every file this generator writes lands here, as does any file whose column order matches.");
        builder.AppendLine("        if ((uint)index < (uint)fileFields.Length");
        builder.AppendLine("            && string.Equals(fileFields[index].Name, expected.Name, global::System.StringComparison.OrdinalIgnoreCase))");
        builder.AppendLine("        {");
        builder.AppendLine("            return fileFields[index];");
        builder.AppendLine("        }");
        builder.AppendLine();
        builder.AppendLine("        // Only a file whose column order differs reaches here. The name index is built at most once");
        builder.AppendLine("        // per read and reused for every subsequent miss, so even a fully reordered schema costs O(n)");
        builder.AppendLine("        // in total rather than a linear scan per field.");
        builder.AppendLine("        if (byName is null)");
        builder.AppendLine("        {");
        builder.AppendLine("            byName = new global::System.Collections.Generic.Dictionary<string, global::Parquet.Schema.DataField>(");
        builder.AppendLine("                fileFields.Length, global::System.StringComparer.OrdinalIgnoreCase);");
        builder.AppendLine("            for (int i = 0; i < fileFields.Length; i++)");
        builder.AppendLine("            {");
        builder.AppendLine("                // First occurrence wins if a file carries duplicate column names. Dictionary.TryAdd is");
        builder.AppendLine("                // not available to netstandard2.0 consumers, hence the explicit containment check.");
        builder.AppendLine("                if (!byName.ContainsKey(fileFields[i].Name))");
        builder.AppendLine("                {");
        builder.AppendLine("                    byName.Add(fileFields[i].Name, fileFields[i]);");
        builder.AppendLine("                }");
        builder.AppendLine("            }");
        builder.AppendLine("        }");
        builder.AppendLine();
        builder.AppendLine("        return byName.TryGetValue(expected.Name, out var match) ? match : expected;");
        builder.AppendLine("    }");
    }

    /// <summary>
    /// Emits the row-group size resolution shared by the two batched write entry points.
    /// </summary>
    private static void EmitRowGroupSizeResolution(StringBuilder builder)
    {
        // The old form was `options.RowGroupSize > 0 && options.RowGroupSize != 50_000 ? ... : rowGroupSize`,
        // which used the default value as a sentinel for "unset". Two consequences: setting
        // RowGroupSize to exactly 50,000 was indistinguishable from not setting it, and whenever
        // options *did* carry a size it silently overrode the explicit method argument — the more
        // specific value losing to the more general one. A nullable parameter says "unset" without
        // borrowing a legal value to mean it, so the precedence can be the obvious one: the explicit
        // argument wins, then options, then the options default.
        builder.AppendLine("        if (rowGroupSize.HasValue && rowGroupSize.Value <= 0)");
        builder.AppendLine("            throw new global::System.ArgumentOutOfRangeException(nameof(rowGroupSize));");
        builder.AppendLine();
        builder.AppendLine("        options ??= global::Parquet.SourceGenerator.ParquetSerializerOptions.Default;");
        builder.AppendLine("        int targetChunkSize = rowGroupSize ?? options.RowGroupSize;");
        builder.AppendLine("        if (targetChunkSize <= 0)");
        builder.AppendLine("            throw new global::System.ArgumentOutOfRangeException(nameof(options), \"ParquetSerializerOptions.RowGroupSize must be greater than zero.\");");
    }

    private static void EmitBuildFormatOptions(StringBuilder builder)
    {
        builder.AppendLine("    /// <summary>");
        builder.AppendLine("    /// Translates the generator's options into the Parquet.Net options the writer accepts.");
        builder.AppendLine("    /// </summary>");
        builder.AppendLine("    private static global::Parquet.ParquetOptions BuildFormatOptions(");
        builder.AppendLine("        global::Parquet.SourceGenerator.ParquetSerializerOptions options)");
        builder.AppendLine("    {");
        builder.AppendLine("        var formatOptions = new global::Parquet.ParquetOptions");
        builder.AppendLine("        {");
        builder.AppendLine("            CompressionMethod = options.CompressionMethod switch");
        builder.AppendLine("            {");
        builder.AppendLine("                global::Parquet.SourceGenerator.ParquetCompressionMethod.None =>");
        builder.AppendLine("                    global::Parquet.CompressionMethod.None,");
        builder.AppendLine("                global::Parquet.SourceGenerator.ParquetCompressionMethod.Gzip =>");
        builder.AppendLine("                    global::Parquet.CompressionMethod.Gzip,");
        builder.AppendLine("                // Parquet.Net spells this one in caps.");
        builder.AppendLine("                global::Parquet.SourceGenerator.ParquetCompressionMethod.Lz4 =>");
        builder.AppendLine("                    global::Parquet.CompressionMethod.LZ4,");
        builder.AppendLine("                global::Parquet.SourceGenerator.ParquetCompressionMethod.Brotli =>");
        builder.AppendLine("                    global::Parquet.CompressionMethod.Brotli,");
        builder.AppendLine("                global::Parquet.SourceGenerator.ParquetCompressionMethod.Zstd =>");
        builder.AppendLine("                    global::Parquet.CompressionMethod.Zstd,");
        builder.AppendLine("                _ => global::Parquet.CompressionMethod.Snappy,");
        builder.AppendLine("            },");
        builder.AppendLine("        };");
        builder.AppendLine();
        // Assigned only when the caller asked for one, so "unspecified" keeps Parquet.Net's own
        // default (SmallestSize) rather than this generator silently picking a level for them.
        builder.AppendLine("        if (options.CompressionLevel.HasValue)");
        builder.AppendLine("        {");
        builder.AppendLine("            formatOptions.CompressionLevel = options.CompressionLevel.Value switch");
        builder.AppendLine("            {");
        builder.AppendLine("                global::Parquet.SourceGenerator.ParquetCompressionLevel.Optimal =>");
        builder.AppendLine("                    global::System.IO.Compression.CompressionLevel.Optimal,");
        builder.AppendLine("                global::Parquet.SourceGenerator.ParquetCompressionLevel.Fastest =>");
        builder.AppendLine("                    global::System.IO.Compression.CompressionLevel.Fastest,");
        builder.AppendLine("                global::Parquet.SourceGenerator.ParquetCompressionLevel.NoCompression =>");
        builder.AppendLine("                    global::System.IO.Compression.CompressionLevel.NoCompression,");
        builder.AppendLine("                _ => global::System.IO.Compression.CompressionLevel.SmallestSize,");
        builder.AppendLine("            };");
        builder.AppendLine("        }");
        builder.AppendLine();
        builder.AppendLine("        return formatOptions;");
        builder.AppendLine("    }");
    }

