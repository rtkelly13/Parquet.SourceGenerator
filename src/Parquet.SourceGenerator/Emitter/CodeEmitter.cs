            $"        if (rowGroupCount == 0) return global::System.Array.Empty<{model.ClassName}>();"
        );
        builder.AppendLine();
        RowGroupLayoutComponent.EmitLayoutProbe(
            builder,
            "reader",
            "totalRows",
            "maxRowCount",
            "rowGroupCount",
            declareRowGroupCount: false
        );
        builder.AppendLine();
        builder.AppendLine($"        var results = new {model.ClassName}[totalRows];");
        builder.AppendLine("        int currentOffset = 0;");
        builder.AppendLine("        var fileFields = reader.Schema.DataFields;");
        builder.AppendLine(
            "        global::System.Collections.Generic.Dictionary<string, global::Parquet.Schema.DataField>? fieldsByName = null;"
        );
        builder.AppendLine();

        for (int i = 0; i < model.Properties.Length; i++)
        {
            builder.AppendLine(
                $"        var field_{i} = ResolveSchemaField(fileFields, {i}, _field_{i}, ref fieldsByName);"
            );
        }

        builder.AppendLine();
        BufferPoolComponent.EmitRentals(builder, model, "maxRowCount");
        builder.AppendLine();

        StringDeduplicatorComponent.EmitDeduplicatorDeclaration(builder, model);

        builder.AppendLine("        try");
        builder.AppendLine("        {");
        builder.AppendLine("            for (int r = 0; r < rowGroupCount; r++)");
        builder.AppendLine("            {");
        builder.AppendLine("                cancellationToken.ThrowIfCancellationRequested();");
        builder.AppendLine("                using var groupReader = reader.OpenRowGroupReader(r);");
        builder.AppendLine("                int rowCount = (int)groupReader.RowCount;");
        builder.AppendLine("                if (rowCount == 0) continue;");
        builder.AppendLine();

        for (int i = 0; i < model.Properties.Length; i++)
        {
            PropertyModel prop = model.Properties[i];
            builder.AppendLine(GetReadPrimitiveCall(prop, $"field_{i}", $"buffer_{i}"));
        }

        builder.AppendLine();
        PropertyMappingComponent.EmitArrayMaterialization(
            builder,
            model,
            "results",
            "currentOffset",
            indent: "                "
        );
        builder.AppendLine("                currentOffset += rowCount;");
        builder.AppendLine("            }");
        builder.AppendLine("        }");
        builder.AppendLine("        finally");
        builder.AppendLine("        {");

        BufferPoolComponent.EmitReturns(builder, model);

        builder.AppendLine("        }");
        builder.AppendLine();
        builder.AppendLine("        return results;");
        builder.AppendLine("    }");
    }

