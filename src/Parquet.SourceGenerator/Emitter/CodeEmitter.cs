    private static void EmitWriteRowGroupAsync(StringBuilder builder, TargetClassModel model)
    {
        builder.AppendLine("    /// <summary>");
        builder.AppendLine(
            $"    /// Writes a single row group chunk using Parquet.Net low-level primitives for maximum speed and Native AOT compatibility."
        );
        builder.AppendLine("    /// </summary>");
        builder.AppendLine(
            $"    public static async global::System.Threading.Tasks.Task WriteParquetRowGroupAsync("
        );
        builder.AppendLine($"        this global::Parquet.ParquetWriter writer,");
        builder.AppendLine(
            $"        global::System.Collections.Generic.IReadOnlyCollection<{model.ClassName}> chunk,"
        );
        builder.AppendLine(
            $"        global::System.Threading.CancellationToken cancellationToken = default)"
        );
        builder.AppendLine("    {");
        builder.AppendLine(
            "        if (writer == null) throw new global::System.ArgumentNullException(nameof(writer));"
        );
        builder.AppendLine(
            "        if (chunk == null) throw new global::System.ArgumentNullException(nameof(chunk));"
        );
        builder.AppendLine();
        builder.AppendLine("        int count = chunk.Count;");
        builder.AppendLine("        if (count == 0) return;");
        builder.AppendLine();

        BufferPoolComponent.EmitWriteRentals(builder, model, "count");

        builder.AppendLine();
        builder.AppendLine("        try");
        builder.AppendLine("        {");

        if (PropertyMappingComponent.IsSingleFieldBlittableStruct(model))
        {
            string elemType = PropertyMappingComponent.GetSingleFieldBufferElementType(model);
            PropertyModel prop = model.Properties[0];
            builder.AppendLine(
                $"            if (chunk is global::System.Collections.Generic.List<{model.ClassName}> listItems)"
            );
            builder.AppendLine("            {");
            builder.AppendLine("#if NET6_0_OR_GREATER");
            builder.AppendLine(
                $"                if (global::System.Runtime.CompilerServices.Unsafe.SizeOf<{model.ClassName}>() == global::System.Runtime.CompilerServices.Unsafe.SizeOf<{elemType}>())"
            );
            builder.AppendLine("                {");
            builder.AppendLine(
                "                    var span = global::System.Runtime.InteropServices.CollectionsMarshal.AsSpan(listItems);"
            );
            builder.AppendLine(
                $"                    global::System.Runtime.InteropServices.MemoryMarshal.Cast<{model.ClassName}, {elemType}>(span.Slice(0, count))"
            );
            builder.AppendLine("                        .CopyTo(buffer_0.AsSpan(0, count));");
            builder.AppendLine("                }");
            builder.AppendLine("                else");
            builder.AppendLine("                {");
            builder.AppendLine("                    for (int i = 0; i < count; i++)");
            builder.AppendLine("                    {");
            builder.AppendLine($"                        buffer_0[i] = listItems[i].{prop.Name};");
            builder.AppendLine("                    }");
            builder.AppendLine("                }");
            builder.AppendLine("#else");
            builder.AppendLine("                for (int i = 0; i < count; i++)");
            builder.AppendLine("                {");
            builder.AppendLine($"                    var item = listItems[i];");
            EmitPropertyAssignments(builder, model, "buffer_", prefix: "                    ");
            builder.AppendLine("                }");
            builder.AppendLine("#endif");
            builder.AppendLine("            }");
            builder.AppendLine($"            else if (chunk is {model.ClassName}[] arrayItems)");
            builder.AppendLine("            {");
            builder.AppendLine("#if NET6_0_OR_GREATER");
            builder.AppendLine(
                $"                if (global::System.Runtime.CompilerServices.Unsafe.SizeOf<{model.ClassName}>() == global::System.Runtime.CompilerServices.Unsafe.SizeOf<{elemType}>())"
            );
            builder.AppendLine("                {");
            builder.AppendLine(
                $"                    global::System.Runtime.InteropServices.MemoryMarshal.Cast<{model.ClassName}, {elemType}>(arrayItems.AsSpan(0, count))"
            );
            builder.AppendLine("                        .CopyTo(buffer_0.AsSpan(0, count));");
            builder.AppendLine("                }");
            builder.AppendLine("                else");
            builder.AppendLine("                {");
            builder.AppendLine("                    for (int i = 0; i < count; i++)");
            builder.AppendLine("                    {");
            builder.AppendLine($"                        buffer_0[i] = arrayItems[i].{prop.Name};");
            builder.AppendLine("                    }");
            builder.AppendLine("                }");
            builder.AppendLine("#else");
            builder.AppendLine("                for (int i = 0; i < count; i++)");
            builder.AppendLine("                {");
            builder.AppendLine($"                    buffer_0[i] = arrayItems[i].{prop.Name};");
            builder.AppendLine("                }");
            builder.AppendLine("#endif");
            builder.AppendLine("            }");
            builder.AppendLine("            else");
            builder.AppendLine("            {");
            builder.AppendLine("                int idx = 0;");
            builder.AppendLine("                foreach (var item in chunk)");
            builder.AppendLine("                {");
            EmitPropertyAssignmentsIndexed(
                builder,
                model,
                "buffer_",
                prefix: "                    "
            );
            builder.AppendLine("                    idx++;");
            builder.AppendLine("                }");
            builder.AppendLine("            }");
        }
        else
        {
            // List fast path
            builder.AppendLine(
                $"            if (chunk is global::System.Collections.Generic.List<{model.ClassName}> listItems)"
            );
            builder.AppendLine("            {");
            builder.AppendLine("#if NET6_0_OR_GREATER");
            builder.AppendLine("                void ExtractSpan()");
            builder.AppendLine("                {");
            builder.AppendLine(
                "                    var span = global::System.Runtime.InteropServices.CollectionsMarshal.AsSpan(listItems);"
            );
            builder.AppendLine("                    for (int i = 0; i < count; i++)");
            builder.AppendLine("                    {");
            builder.AppendLine("                        var item = span[i];");
            EmitPropertyAssignments(builder, model, "buffer_", prefix: "                        ");
            builder.AppendLine("                    }");
            builder.AppendLine("                }");
            builder.AppendLine("                ExtractSpan();");
            builder.AppendLine("#else");
            builder.AppendLine("                for (int i = 0; i < count; i++)");
            builder.AppendLine("                {");
            builder.AppendLine($"                    var item = listItems[i];");
            EmitPropertyAssignments(builder, model, "buffer_", prefix: "                    ");
            builder.AppendLine("                }");
            builder.AppendLine("#endif");
            builder.AppendLine("            }");

            // Array fast path
            builder.AppendLine($"            else if (chunk is {model.ClassName}[] arrayItems)");
            builder.AppendLine("            {");
            builder.AppendLine("                for (int i = 0; i < count; i++)");
            builder.AppendLine("                {");
            builder.AppendLine($"                    var item = arrayItems[i];");
            EmitPropertyAssignments(builder, model, "buffer_", prefix: "                    ");
            builder.AppendLine("                }");
            builder.AppendLine("            }");

            // Enumerable fallback
            builder.AppendLine("            else");
            builder.AppendLine("            {");
            builder.AppendLine("                int idx = 0;");
            builder.AppendLine("                foreach (var item in chunk)");
            builder.AppendLine("                {");
            EmitPropertyAssignmentsIndexed(
                builder,
                model,
                "buffer_",
                prefix: "                    "
            );
            builder.AppendLine("                    idx++;");
            builder.AppendLine("                }");
            builder.AppendLine("            }");
        }
        builder.AppendLine();

        // Write row group using static pre-allocated DataFields
        builder.AppendLine("            using (var groupWriter = writer.CreateRowGroup())");
        builder.AppendLine("            {");

        for (int i = 0; i < model.Properties.Length; i++)
        {
            PropertyModel prop = model.Properties[i];
            string fieldAccess = $"_field_{i}";
            builder.AppendLine(GetWritePrimitiveCall(prop, fieldAccess, $"buffer_{i}", i));
            BufferPoolComponent.EmitSingleWriteReturn(
                builder,
                prop,
                i,
                "buffer_",
                indent: "                "
            );
        }

        builder.AppendLine("            }");
        builder.AppendLine("        }");
        builder.AppendLine("        finally");
        builder.AppendLine("        {");

        BufferPoolComponent.EmitWriteReturns(builder, model);

        builder.AppendLine("        }");
        builder.AppendLine("    }");
    }

    private static void EmitWriteAsync(StringBuilder builder, TargetClassModel model)
    {
        builder.AppendLine("    /// <summary>");
        builder.AppendLine(
            $"    /// Asynchronously serializes all <c>{model.ClassName}</c> items using Parquet.Net low-level primitives."
        );
        builder.AppendLine("    /// </summary>");
        builder.AppendLine(
            $"    public static async global::System.Threading.Tasks.Task WriteParquetAsync("
        );
        builder.AppendLine(
            $"        this global::System.Collections.Generic.IReadOnlyCollection<{model.ClassName}> items,"
        );
        builder.AppendLine($"        global::System.IO.Stream stream,");
        builder.AppendLine(
            $"        global::Parquet.SourceGenerator.ParquetSerializerOptions? options = null,"
        );
        builder.AppendLine(
            $"        global::System.Threading.CancellationToken cancellationToken = default)"
        );
        builder.AppendLine("    {");
        builder.AppendLine(
            "        if (items == null) throw new global::System.ArgumentNullException(nameof(items));"
        );
        builder.AppendLine(
            "        if (stream == null) throw new global::System.ArgumentNullException(nameof(stream));"
        );
        builder.AppendLine("        cancellationToken.ThrowIfCancellationRequested();");
        builder.AppendLine();
        builder.AppendLine(
            "        options ??= global::Parquet.SourceGenerator.ParquetSerializerOptions.Default;"
        );
        builder.AppendLine();
        builder.AppendLine(
            "        await using var writer = await global::Parquet.ParquetWriter.CreateAsync("
        );
        builder.AppendLine("            Schema,");
        builder.AppendLine("            stream,");
        builder.AppendLine("            BuildFormatOptions(options),");
        builder.AppendLine("            cancellationToken: cancellationToken);");
        builder.AppendLine(
            "        await writer.WriteParquetRowGroupAsync(items, cancellationToken);"
        );
        builder.AppendLine("    }");
    }

    private static void EmitWriteBatchedAsync(StringBuilder builder, TargetClassModel model)
    {
        builder.AppendLine("    /// <summary>");
        builder.AppendLine(
            $"    /// Streams <c>{model.ClassName}</c> items into a Parquet file in fixed-size row group batches using low-level primitives."
        );
        builder.AppendLine("    /// </summary>");
        builder.AppendLine(
            $"    public static async global::System.Threading.Tasks.Task WriteParquetBatchedAsync("
        );
        builder.AppendLine(
            $"        this global::System.Collections.Generic.IEnumerable<{model.ClassName}> items,"
        );
        builder.AppendLine($"        global::System.IO.Stream stream,");
        builder.AppendLine($"        int? rowGroupSize = null,");
        builder.AppendLine(
            $"        global::Parquet.SourceGenerator.ParquetSerializerOptions? options = null,"
        );
        builder.AppendLine(
            $"        global::System.Threading.CancellationToken cancellationToken = default)"
        );
        builder.AppendLine("    {");
