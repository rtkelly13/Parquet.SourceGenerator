using System;
using System.Text;
using Parquet.SourceGenerator.Models;

namespace Parquet.SourceGenerator.Emitter;

/// <summary>
/// Emits high-performance C# partial extension classes targeting Parquet.Net v6 low-level primitives.
/// Features configurable ParquetSerializerOptions, IAsyncEnumerable streaming, compact 8-byte Int64 microsecond timestamp encoding,
/// parallel multi-row-group reading, zero-allocation Guid binary encoding, static pre-allocated DataFields,
/// O(1) index-check schema field resolution, ArrayPool buffer recycling, zero-copy ReadOnlyMemory overloads,
/// and Native AOT compatibility.
/// </summary>
public static class CodeEmitter
{
    /// <summary>
    /// Generates complete C# source code string for a given target model.
    /// </summary>
    public static string EmitSource(TargetClassModel model)
    {
        var builder = new StringBuilder();

        builder.AppendLine("// <auto-generated />");
        builder.AppendLine("#nullable enable");
        builder.AppendLine("#pragma warning disable CS8600, CS8601, CS8602, CS8603, CS8604, CS8629");
        builder.AppendLine();

        if (!string.IsNullOrEmpty(model.Namespace))
        {
            builder.AppendLine($"namespace {model.Namespace};");
            builder.AppendLine();
        }

        string extensionsClassName = $"{model.ClassName}ParquetExtensions";

        builder.AppendLine($"public static partial class {extensionsClassName}");
        builder.AppendLine("{");

        EmitSchema(builder, model);
        builder.AppendLine();

        EmitStaticFields(builder, model);
        builder.AppendLine();

        if (model.Properties.Length > 0)
        {
            EmitResolveSchemaField(builder);
            builder.AppendLine();
        }

        EmitBuildFormatOptions(builder);
        builder.AppendLine();

        // Streaming row group writer — low level primitives, 100M+ scale, Native AOT compatible
        EmitWriteRowGroupAsync(builder, model);
        builder.AppendLine();

        // Primary write API — async (v6 requires async for writer creation)
        EmitWriteAsync(builder, model);
        builder.AppendLine();

        // Batched streaming write — splits IEnumerable into fixed-size row groups
        EmitWriteBatchedAsync(builder, model);
        builder.AppendLine();

        // IAsyncEnumerable streaming write
        EmitWriteAsyncEnumerable(builder, model);
        builder.AppendLine();

        // Read API — async (v6 low-level primitives)
        EmitReadAsync(builder, model);
        builder.AppendLine();

        // Parallel Read API — multi-core parallel object instantiation
        EmitReadParallelAsync(builder, model);
        builder.AppendLine();

        // Streaming Read API — IAsyncEnumerable streaming
        EmitReadStreamAsync(builder, model);
        builder.AppendLine();

        // Zero-copy ReadOnlyMemory overloads
        EmitReadMemoryOverloads(builder, model);

        builder.AppendLine("}");

        return builder.ToString();
    }

    // ──────────────────────────────────────────────────────────
    //  SCHEMA & STATIC FIELD CACHING
    // ──────────────────────────────────────────────────────────

    private static void EmitSchema(StringBuilder builder, TargetClassModel model)
    {
        builder.AppendLine("    /// <summary>");
        builder.AppendLine($"    /// Static compile-time <c>Parquet.Schema.ParquetSchema</c> for <c>{model.ClassName}</c>.");
        builder.AppendLine("    /// </summary>");
        builder.AppendLine("    public static readonly global::Parquet.Schema.ParquetSchema Schema = new global::Parquet.Schema.ParquetSchema(");

        for (int i = 0; i < model.Properties.Length; i++)
        {
            PropertyModel prop = model.Properties[i];
            string comma = i < model.Properties.Length - 1 ? "," : "";
            builder.AppendLine($"        {GetFieldCreationExpression(prop)}{comma}");
        }

        builder.AppendLine("    );");
    }

    private static void EmitStaticFields(StringBuilder builder, TargetClassModel model)
    {
        for (int i = 0; i < model.Properties.Length; i++)
        {
            builder.AppendLine($"    private static readonly global::Parquet.Schema.DataField _field_{i} = (global::Parquet.Schema.DataField)Schema.Fields[{i}];");
        }
    }

    private static string GetFieldCreationExpression(PropertyModel prop)
    {
        // The column name comes from user source — `[ParquetColumn("...")]` — so it can contain
        // anything a C# string literal can, including quotes and backslashes. Interpolating it raw
        // into the emitted literal produced generated code that would not parse, and reported the
        // error against the generated file rather than the attribute that caused it.
        // FormatLiteral emits the surrounding quotes and escapes the contents, so callers below
        // interpolate `name` without adding quotes of their own.
        string name = Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(prop.ParquetColumnName, quote: true);

        return prop.Kind switch
        {
            PropertyKind.Decimal when prop.DecimalPrecision.HasValue && prop.DecimalScale.HasValue =>
                $"new global::Parquet.Schema.DecimalDataField({name}, {prop.DecimalPrecision.Value}, {prop.DecimalScale.Value}, isNullable: {BoolLiteral(prop.IsNullable)})",

            PropertyKind.Decimal =>
                $"new global::Parquet.Schema.DecimalDataField({name}, 38, 18, isNullable: {BoolLiteral(prop.IsNullable)})",

            PropertyKind.DateTime when prop.TimestampUnit == "1" || prop.TimestampUnit?.Contains("Microseconds") == true =>
                $"new global::Parquet.Schema.DateTimeDataField({name}, global::Parquet.Schema.DateTimeFormat.DateAndTimeMicros, isNullable: {BoolLiteral(prop.IsNullable)})",

            PropertyKind.DateTime =>
                $"new global::Parquet.Schema.DateTimeDataField({name}, global::Parquet.Schema.DateTimeFormat.Impala, isNullable: {BoolLiteral(prop.IsNullable)})",

            PropertyKind.TimeSpan =>
                $"new global::Parquet.Schema.TimeSpanDataField({name}, global::Parquet.Schema.TimeSpanFormat.MilliSeconds, isNullable: {BoolLiteral(prop.IsNullable)})",

            PropertyKind.Guid =>
                $"new global::Parquet.Schema.DataField({name}, typeof(global::System.Guid), isNullable: {BoolLiteral(prop.IsNullable)})",

            PropertyKind.Enum =>
                $"new global::Parquet.Schema.DataField({name}, typeof({prop.EnumUnderlyingTypeName ?? "int"}), isNullable: {BoolLiteral(prop.IsNullable)})",

            PropertyKind.ByteArray =>
                $"new global::Parquet.Schema.DataField({name}, typeof(byte[]), isNullable: {BoolLiteral(prop.IsNullable)})",

            _ =>
                $"new global::Parquet.Schema.DataField({name}, typeof({prop.TypeName.TrimEnd('?')}), isNullable: {BoolLiteral(prop.IsNullable)})",
        };
    }

    // ──────────────────────────────────────────────────────────
    //  WRITE ROW GROUP (Low-Level Primitives, Static Field Access)
    // ──────────────────────────────────────────────────────────

    private static void EmitWriteRowGroupAsync(StringBuilder builder, TargetClassModel model)
    {
        builder.AppendLine("    /// <summary>");
        builder.AppendLine($"    /// Writes a single row group chunk using Parquet.Net low-level primitives for maximum speed and Native AOT compatibility.");
        builder.AppendLine("    /// </summary>");
        builder.AppendLine($"    public static async global::System.Threading.Tasks.Task WriteParquetRowGroupAsync(");
        builder.AppendLine($"        this global::Parquet.ParquetWriter writer,");
        builder.AppendLine($"        global::System.Collections.Generic.IReadOnlyCollection<{model.ClassName}> chunk,");
        builder.AppendLine($"        global::System.Threading.CancellationToken cancellationToken = default)");
        builder.AppendLine("    {");
        builder.AppendLine("        if (writer == null) throw new global::System.ArgumentNullException(nameof(writer));");
        builder.AppendLine("        if (chunk == null) throw new global::System.ArgumentNullException(nameof(chunk));");
        builder.AppendLine();
        builder.AppendLine("        int count = chunk.Count;");
        builder.AppendLine("        if (count == 0) return;");
        builder.AppendLine();

        for (int i = 0; i < model.Properties.Length; i++)
        {
            PropertyModel prop = model.Properties[i];
            string bufType = GetBufferElementType(prop);
            builder.AppendLine($"        var buffer_{i} = global::System.Buffers.ArrayPool<{bufType}>.Shared.Rent(count);");
        }

        builder.AppendLine();
        builder.AppendLine("        try");
        builder.AppendLine("        {");

        // List fast path
        builder.AppendLine($"            if (chunk is global::System.Collections.Generic.List<{model.ClassName}> listItems)");
        builder.AppendLine("            {");
        builder.AppendLine("                var span = global::System.Runtime.InteropServices.CollectionsMarshal.AsSpan(listItems);");
        builder.AppendLine("                for (int i = 0; i < count; i++)");
        builder.AppendLine("                {");
        builder.AppendLine("                    var item = span[i];");
        EmitPropertyAssignments(builder, model, "buffer_", prefix: "                    ");
        builder.AppendLine("                }");
        builder.AppendLine("            }");

        // Array fast path
        builder.AppendLine($"            else if (chunk is {model.ClassName}[] arrayItems)");
        builder.AppendLine("            {");
        builder.AppendLine("                for (int i = 0; i < count; i++)");
        builder.AppendLine("                {");
        builder.AppendLine($"                    var item = arrayItems[i];");
        EmitPropertyAssignments(builder, model, "buffer_", prefix: "                    ");
        builder.AppendLine("                }");
        builder.AppendLine("            }");

        // Enumerable fallback
        builder.AppendLine("            else");
        builder.AppendLine("            {");
        builder.AppendLine("                int idx = 0;");
        builder.AppendLine("                foreach (var item in chunk)");
        builder.AppendLine("                {");
        EmitPropertyAssignmentsIndexed(builder, model, "buffer_", prefix: "                    ");
        builder.AppendLine("                    idx++;");
        builder.AppendLine("                }");
        builder.AppendLine("            }");
        builder.AppendLine();

        // Write row group using static pre-allocated DataFields
        builder.AppendLine("            using (var groupWriter = writer.CreateRowGroup())");
        builder.AppendLine("            {");

        for (int i = 0; i < model.Properties.Length; i++)
        {
            PropertyModel prop = model.Properties[i];
            string fieldAccess = $"_field_{i}";
            string writeCall = GetWritePrimitiveCall(prop, fieldAccess, $"buffer_{i}");
            builder.AppendLine($"                {writeCall}");
        }

        builder.AppendLine("            }");
        builder.AppendLine("        }");
        builder.AppendLine("        finally");
        builder.AppendLine("        {");

        for (int i = 0; i < model.Properties.Length; i++)
        {
            PropertyModel prop = model.Properties[i];
            string bufType = GetBufferElementType(prop);
            bool isRef = IsReferenceTypeBuffer(prop);
            string clearArg = isRef ? "clearArray: true" : "clearArray: false";
            builder.AppendLine($"            global::System.Buffers.ArrayPool<{bufType}>.Shared.Return(buffer_{i}, {clearArg});");
        }

        builder.AppendLine("        }");
        builder.AppendLine("    }");
    }

    // ──────────────────────────────────────────────────────────
    //  WRITE (full collection with options)
    // ──────────────────────────────────────────────────────────

    private static void EmitWriteAsync(StringBuilder builder, TargetClassModel model)
    {
        builder.AppendLine("    /// <summary>");
        builder.AppendLine($"    /// Asynchronously serializes all <c>{model.ClassName}</c> items using Parquet.Net low-level primitives.");
        builder.AppendLine("    /// </summary>");
        builder.AppendLine($"    public static async global::System.Threading.Tasks.Task WriteParquetAsync(");
        builder.AppendLine($"        this global::System.Collections.Generic.IReadOnlyCollection<{model.ClassName}> items,");
        builder.AppendLine($"        global::System.IO.Stream stream,");
        builder.AppendLine($"        global::Parquet.SourceGenerator.ParquetSerializerOptions? options = null,");
        builder.AppendLine($"        global::System.Threading.CancellationToken cancellationToken = default)");
        builder.AppendLine("    {");
        builder.AppendLine("        if (items == null) throw new global::System.ArgumentNullException(nameof(items));");
        builder.AppendLine("        if (stream == null) throw new global::System.ArgumentNullException(nameof(stream));");
        builder.AppendLine("        cancellationToken.ThrowIfCancellationRequested();");
        builder.AppendLine();
        builder.AppendLine("        options ??= global::Parquet.SourceGenerator.ParquetSerializerOptions.Default;");
        builder.AppendLine();
        builder.AppendLine("        await using var writer = await global::Parquet.ParquetWriter.CreateAsync(Schema, stream, BuildFormatOptions(options), cancellationToken: cancellationToken);");
        builder.AppendLine("        await writer.WriteParquetRowGroupAsync(items, cancellationToken);");
        builder.AppendLine("    }");
    }

    // ──────────────────────────────────────────────────────────
    //  WRITE BATCHED (with options)
    // ──────────────────────────────────────────────────────────

    private static void EmitWriteBatchedAsync(StringBuilder builder, TargetClassModel model)
    {
        builder.AppendLine("    /// <summary>");
        builder.AppendLine($"    /// Streams <c>{model.ClassName}</c> items into a Parquet file in fixed-size row group batches using low-level primitives.");
        builder.AppendLine("    /// </summary>");
        builder.AppendLine($"    public static async global::System.Threading.Tasks.Task WriteParquetBatchedAsync(");
        builder.AppendLine($"        this global::System.Collections.Generic.IEnumerable<{model.ClassName}> items,");
        builder.AppendLine($"        global::System.IO.Stream stream,");
        builder.AppendLine($"        int? rowGroupSize = null,");
        builder.AppendLine($"        global::Parquet.SourceGenerator.ParquetSerializerOptions? options = null,");
        builder.AppendLine($"        global::System.Threading.CancellationToken cancellationToken = default)");
        builder.AppendLine("    {");
        builder.AppendLine("        if (items == null) throw new global::System.ArgumentNullException(nameof(items));");
        builder.AppendLine("        if (stream == null) throw new global::System.ArgumentNullException(nameof(stream));");
        EmitRowGroupSizeResolution(builder);
        builder.AppendLine();
        builder.AppendLine("        await using var writer = await global::Parquet.ParquetWriter.CreateAsync(Schema, stream, BuildFormatOptions(options), cancellationToken: cancellationToken);");
        builder.AppendLine($"        var buffer = new global::System.Collections.Generic.List<{model.ClassName}>(targetChunkSize);");
        builder.AppendLine("        foreach (var item in items)");
        builder.AppendLine("        {");
        builder.AppendLine("            cancellationToken.ThrowIfCancellationRequested();");
        builder.AppendLine("            buffer.Add(item);");
        builder.AppendLine("            if (buffer.Count == targetChunkSize)");
        builder.AppendLine("            {");
        builder.AppendLine("                await writer.WriteParquetRowGroupAsync(buffer, cancellationToken);");
        builder.AppendLine("                buffer.Clear();");
        builder.AppendLine("            }");
        builder.AppendLine("        }");
        builder.AppendLine("        if (buffer.Count > 0)");
        builder.AppendLine("            await writer.WriteParquetRowGroupAsync(buffer, cancellationToken);");
        builder.AppendLine("    }");
    }

