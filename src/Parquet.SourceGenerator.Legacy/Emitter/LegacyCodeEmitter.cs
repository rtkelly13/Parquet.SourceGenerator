using System;
using System.Text;
using Parquet.SourceGenerator.Models;

namespace Parquet.SourceGenerator.Legacy.Emitter;

/// <summary>
/// Emits C# partial extension classes targeting Parquet.Net v4 / v5 (DataColumn-based API).
/// Provides compatibility for .NET Framework 4.7.2, .NET Standard 2.0, and Parquet.Net 4.x/5.x releases.
/// </summary>
public static class LegacyCodeEmitter
{
    /// <summary>
    /// Generates complete C# source code string for a target model using Parquet.Net v4/v5 APIs.
    /// </summary>
    public static string EmitSource(TargetClassModel model)
    {
        var builder = new StringBuilder();

        builder.AppendLine("// <auto-generated />");
        builder.AppendLine("#nullable enable");
        builder.AppendLine("#pragma warning disable CS8600, CS8601, CS8602, CS8603, CS8604, CS8629");
        builder.AppendLine();

        if (!string.IsNullOrEmpty(model.Namespace))
        {
            builder.AppendLine($"namespace {model.Namespace};");
            builder.AppendLine();
        }

        string extensionsClassName = $"{model.ClassName}ParquetLegacyExtensions";

        builder.AppendLine($"public static partial class {extensionsClassName}");
        builder.AppendLine("{");

        EmitSchema(builder, model);
        builder.AppendLine();

        EmitStaticFields(builder, model);
        builder.AppendLine();

        if (model.Properties.Length > 0)
        {
            EmitResolveSchemaField(builder);
            builder.AppendLine();
        }

        EmitBuildFormatOptions(builder);
        builder.AppendLine();

        EmitWriteRowGroupAsync(builder, model);
        builder.AppendLine();

        EmitWriteAsync(builder, model);
        builder.AppendLine();

        EmitWriteBatchedAsync(builder, model);
        builder.AppendLine();

        EmitReadAsync(builder, model);
        builder.AppendLine();

        builder.AppendLine("}");

        return builder.ToString();
    }

    private static void EmitSchema(StringBuilder builder, TargetClassModel model)
    {
        builder.AppendLine("    /// <summary>");
        builder.AppendLine($"    /// Static compile-time <c>Parquet.Schema.ParquetSchema</c> for <c>{model.ClassName}</c>.");
        builder.AppendLine("    /// </summary>");
        builder.AppendLine("    public static readonly global::Parquet.Schema.ParquetSchema Schema = new global::Parquet.Schema.ParquetSchema(");

        for (int i = 0; i < model.Properties.Length; i++)
        {
            PropertyModel prop = model.Properties[i];
            string comma = i < model.Properties.Length - 1 ? "," : "";
            string name = Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(prop.ParquetColumnName, quote: true);

            string fieldInstantiation = prop.Kind switch
            {
                PropertyKind.Decimal when prop.DecimalPrecision.HasValue && prop.DecimalScale.HasValue =>
                    $"new global::Parquet.Schema.DecimalDataField({name}, {prop.DecimalPrecision.Value}, {prop.DecimalScale.Value}, isNullable: {BoolLiteral(prop.IsNullable)})",
                PropertyKind.Decimal =>
                    $"new global::Parquet.Schema.DecimalDataField({name}, 38, 18, isNullable: {BoolLiteral(prop.IsNullable)})",
                PropertyKind.DateTime when prop.TimestampUnit == "1" || prop.TimestampUnit?.Contains("Microseconds") == true =>
                    $"new global::Parquet.Schema.DateTimeDataField({name}, global::Parquet.Schema.DateTimeFormat.DateAndTimeMicros, isNullable: {BoolLiteral(prop.IsNullable)})",
                PropertyKind.DateTime =>
                    $"new global::Parquet.Schema.DateTimeDataField({name}, global::Parquet.Schema.DateTimeFormat.Impala, isNullable: {BoolLiteral(prop.IsNullable)})",
                PropertyKind.TimeSpan =>
                    $"new global::Parquet.Schema.TimeSpanDataField({name}, global::Parquet.Schema.TimeSpanFormat.MilliSeconds, isNullable: {BoolLiteral(prop.IsNullable)})",
                PropertyKind.Guid =>
                    $"new global::Parquet.Schema.DataField({name}, typeof(global::System.Guid), isNullable: {BoolLiteral(prop.IsNullable)})",
                PropertyKind.Enum =>
                    $"new global::Parquet.Schema.DataField({name}, typeof({prop.EnumUnderlyingTypeName ?? "int"}), isNullable: {BoolLiteral(prop.IsNullable)})",
                PropertyKind.ByteArray =>
                    $"new global::Parquet.Schema.DataField({name}, typeof(byte[]), isNullable: {BoolLiteral(prop.IsNullable)})",
                _ =>
                    $"new global::Parquet.Schema.DataField({name}, typeof({prop.TypeName.TrimEnd('?')}), isNullable: {BoolLiteral(prop.IsNullable)})",
            };

            builder.AppendLine($"        {fieldInstantiation}{comma}");
        }

        builder.AppendLine("    );");
    }

    private static void EmitStaticFields(StringBuilder builder, TargetClassModel model)
    {
        for (int i = 0; i < model.Properties.Length; i++)
        {
            builder.AppendLine($"    private static readonly global::Parquet.Schema.DataField _field_{i} = (global::Parquet.Schema.DataField)Schema.Fields[{i}];");
        }
    }

    private static void EmitWriteRowGroupAsync(StringBuilder builder, TargetClassModel model)
    {
        builder.AppendLine("    /// <summary>");
        builder.AppendLine($"    /// Writes a single row group chunk using Parquet.Net DataColumn primitives.");
        builder.AppendLine("    /// </summary>");
        builder.AppendLine("    public static async global::System.Threading.Tasks.Task WriteRowGroupAsync(");
        builder.AppendLine("        this global::Parquet.ParquetWriter writer,");
        builder.AppendLine($"        global::System.Collections.Generic.IReadOnlyList<{model.ClassName}> items,");
        builder.AppendLine("        global::System.Threading.CancellationToken cancellationToken = default)");
        builder.AppendLine("    {");

        if (model.Properties.Length == 0)
        {
            builder.AppendLine("        using var rgWriter = writer.CreateRowGroup();");
            builder.AppendLine("        await global::System.Threading.Tasks.Task.CompletedTask;");
            builder.AppendLine("    }");
            return;
        }

        builder.AppendLine("        int count = items.Count;");
        builder.AppendLine();

        for (int i = 0; i < model.Properties.Length; i++)
        {
            PropertyModel prop = model.Properties[i];
            string arrayType = GetArrayTypeName(prop);
            builder.AppendLine($"        var colArray_{i} = new {arrayType}[count];");
        }

        builder.AppendLine();
        builder.AppendLine("        for (int k = 0; k < count; k++)");
        builder.AppendLine("        {");
        builder.AppendLine("            var item = items[k];");

        for (int i = 0; i < model.Properties.Length; i++)
        {
            PropertyModel prop = model.Properties[i];
            string propAccess = $"item.{prop.Name}";

            if (prop.Kind == PropertyKind.Enum)
            {
                builder.AppendLine($"            colArray_{i}[k] = ({prop.EnumUnderlyingTypeName ?? "int"}){propAccess};");
            }
            else
            {
                builder.AppendLine($"            colArray_{i}[k] = {propAccess};");
            }
        }

        builder.AppendLine("        }");
        builder.AppendLine();
        builder.AppendLine("        using (var rgWriter = writer.CreateRowGroup())");
        builder.AppendLine("        {");

        for (int i = 0; i < model.Properties.Length; i++)
        {
            builder.AppendLine($"            var col_{i} = new global::Parquet.Data.DataColumn(_field_{i}, colArray_{i});");
            builder.AppendLine($"            await rgWriter.WriteColumnAsync(col_{i}, cancellationToken).ConfigureAwait(false);");
        }

        builder.AppendLine("        }");
        builder.AppendLine("    }");
    }

    private static void EmitWriteAsync(StringBuilder builder, TargetClassModel model)
    {
        builder.AppendLine("    /// <summary>");
        builder.AppendLine($"    /// Asynchronously serializes all <c>{model.ClassName}</c> items to stream using Parquet.Net v4/v5.");
        builder.AppendLine("    /// </summary>");
        builder.AppendLine("    public static async global::System.Threading.Tasks.Task WriteParquetAsync(");
        builder.AppendLine($"        this global::System.Collections.Generic.IReadOnlyList<{model.ClassName}> items,");
        builder.AppendLine("        global::System.IO.Stream stream,");
        builder.AppendLine("        global::Parquet.SourceGenerator.ParquetSerializerOptions? options = null,");
        builder.AppendLine("        global::System.Threading.CancellationToken cancellationToken = default)");
        builder.AppendLine("    {");
        builder.AppendLine("        options ??= global::Parquet.SourceGenerator.ParquetSerializerOptions.Default;");
        builder.AppendLine("        using (var writer = await global::Parquet.ParquetWriter.CreateAsync(Schema, stream, BuildFormatOptions(options), cancellationToken: cancellationToken).ConfigureAwait(false))");
        builder.AppendLine("        {");
        builder.AppendLine("            await writer.WriteRowGroupAsync(items, cancellationToken).ConfigureAwait(false);");
        builder.AppendLine("        }");
        builder.AppendLine("    }");
    }

    private static void EmitWriteBatchedAsync(StringBuilder builder, TargetClassModel model)
    {
        builder.AppendLine("    /// <summary>");
        builder.AppendLine($"    /// Asynchronously serializes items in fixed-size row group chunks.");
        builder.AppendLine("    /// </summary>");
        builder.AppendLine("    public static async global::System.Threading.Tasks.Task WriteParquetBatchedAsync(");
        builder.AppendLine($"        this global::System.Collections.Generic.IEnumerable<{model.ClassName}> items,");
        builder.AppendLine("        global::System.IO.Stream stream,");
        builder.AppendLine("        int? rowGroupSize = null,");
        builder.AppendLine("        global::Parquet.SourceGenerator.ParquetSerializerOptions? options = null,");
        builder.AppendLine("        global::System.Threading.CancellationToken cancellationToken = default)");
        builder.AppendLine("    {");
        builder.AppendLine("        options ??= global::Parquet.SourceGenerator.ParquetSerializerOptions.Default;");
        builder.AppendLine("        int batchSize = rowGroupSize ?? options.RowGroupSize;");
        builder.AppendLine("        using (var writer = await global::Parquet.ParquetWriter.CreateAsync(Schema, stream, BuildFormatOptions(options), cancellationToken: cancellationToken).ConfigureAwait(false))");
        builder.AppendLine("        {");
        builder.AppendLine($"            var chunk = new global::System.Collections.Generic.List<{model.ClassName}>(batchSize);");
        builder.AppendLine("            foreach (var item in items)");
        builder.AppendLine("            {");
        builder.AppendLine("                chunk.Add(item);");
        builder.AppendLine("                if (chunk.Count >= batchSize)");
        builder.AppendLine("                {");
        builder.AppendLine("                    await writer.WriteRowGroupAsync(chunk, cancellationToken).ConfigureAwait(false);");
        builder.AppendLine("                    chunk.Clear();");
        builder.AppendLine("                }");
        builder.AppendLine("            }");
        builder.AppendLine("            if (chunk.Count > 0)");
        builder.AppendLine("            {");
        builder.AppendLine("                await writer.WriteRowGroupAsync(chunk, cancellationToken).ConfigureAwait(false);");
        builder.AppendLine("            }");
        builder.AppendLine("        }");
        builder.AppendLine("    }");
    }

    private static void EmitReadAsync(StringBuilder builder, TargetClassModel model)
    {
        builder.AppendLine("    /// <summary>");
        builder.AppendLine($"    /// Asynchronously deserializes all <c>{model.ClassName}</c> objects from a Parquet stream using Parquet.Net v4/v5.");
        builder.AppendLine("    /// </summary>");
        builder.AppendLine($"    public static async global::System.Threading.Tasks.Task<global::System.Collections.Generic.List<{model.ClassName}>> ReadParquetAsync(");
        builder.AppendLine("        global::System.IO.Stream stream,");
        builder.AppendLine("        global::Parquet.SourceGenerator.ParquetSerializerOptions? options = null,");
        builder.AppendLine("        global::System.Threading.CancellationToken cancellationToken = default)");
        builder.AppendLine("    {");
        builder.AppendLine("        options ??= global::Parquet.SourceGenerator.ParquetSerializerOptions.Default;");
        builder.AppendLine("        using (var reader = await global::Parquet.ParquetReader.CreateAsync(stream, cancellationToken: cancellationToken).ConfigureAwait(false))");
        builder.AppendLine("        {");

        if (model.Properties.Length == 0)
        {
            builder.AppendLine($"            var emptyResults = new global::System.Collections.Generic.List<{model.ClassName}>();");
            builder.AppendLine("            return emptyResults;");
            builder.AppendLine("        }");
            builder.AppendLine("    }");
            return;
        }

        builder.AppendLine("            int totalRows = 0;");
        builder.AppendLine("            for (int r = 0; r < reader.RowGroupCount; r++)");
        builder.AppendLine("            {");
        builder.AppendLine("                using var rgReader = reader.OpenRowGroupReader(r);");
        builder.AppendLine("                totalRows += (int)rgReader.RowCount;");
        builder.AppendLine("            }");
        builder.AppendLine();
        builder.AppendLine($"            var results = new global::System.Collections.Generic.List<{model.ClassName}>(totalRows);");
        builder.AppendLine("            global::System.Collections.Generic.Dictionary<string, global::Parquet.Schema.DataField>? fieldsByName = null;");
        builder.AppendLine();
        builder.AppendLine("            for (int r = 0; r < reader.RowGroupCount; r++)");
        builder.AppendLine("            {");
        builder.AppendLine("                using var rgReader = reader.OpenRowGroupReader(r);");
        builder.AppendLine("                int groupRows = (int)rgReader.RowCount;");
        builder.AppendLine("                if (groupRows == 0) continue;");
        builder.AppendLine();

        for (int i = 0; i < model.Properties.Length; i++)
        {
            PropertyModel prop = model.Properties[i];
            string arrayType = GetArrayTypeName(prop);
            builder.AppendLine($"                var resolvedField_{i} = ResolveSchemaField(reader.Schema.GetDataFields(), _field_{i}, ref fieldsByName);");
            builder.AppendLine($"                var col_{i} = await rgReader.ReadColumnAsync(resolvedField_{i}, cancellationToken).ConfigureAwait(false);");
            builder.AppendLine($"                var data_{i} = ({arrayType}[])col_{i}.Data;");
        }

        builder.AppendLine();
        builder.AppendLine("                for (int k = 0; k < groupRows; k++)");
        builder.AppendLine("                {");
        builder.AppendLine($"                    var item = new {model.ClassName}");
        builder.AppendLine("                    {");

        for (int i = 0; i < model.Properties.Length; i++)
        {
            PropertyModel prop = model.Properties[i];
            string comma = i < model.Properties.Length - 1 ? "," : "";
            string dataAccess = $"data_{i}[k]";

            if (prop.Kind == PropertyKind.Enum)
            {
                builder.AppendLine($"                        {prop.Name} = ({prop.TypeName}){dataAccess}{comma}");
            }
            else
            {
                builder.AppendLine($"                        {prop.Name} = {dataAccess}{comma}");
            }
        }

        builder.AppendLine("                    };");
        builder.AppendLine("                    results.Add(item);");
        builder.AppendLine("                }");
        builder.AppendLine("            }");
        builder.AppendLine("            return results;");
        builder.AppendLine("        }");
        builder.AppendLine("    }");
    }

    private static void EmitResolveSchemaField(StringBuilder builder)
    {
        builder.AppendLine("    private static global::Parquet.Schema.DataField ResolveSchemaField(");
        builder.AppendLine("        global::Parquet.Schema.DataField[] fileFields,");
        builder.AppendLine("        global::Parquet.Schema.DataField expected,");
        builder.AppendLine("        ref global::System.Collections.Generic.Dictionary<string, global::Parquet.Schema.DataField>? byName)");
        builder.AppendLine("    {");
        builder.AppendLine("        string expectedPath = expected.Path.ToString();");
        builder.AppendLine("        for (int i = 0; i < fileFields.Length; i++)");
        builder.AppendLine("        {");
        builder.AppendLine("            if (string.Equals(fileFields[i].Path.ToString(), expectedPath, global::System.StringComparison.OrdinalIgnoreCase))");
        builder.AppendLine("                return fileFields[i];");
        builder.AppendLine("        }");
        builder.AppendLine("        if (byName is null)");
        builder.AppendLine("        {");
        builder.AppendLine("            byName = new global::System.Collections.Generic.Dictionary<string, global::Parquet.Schema.DataField>(fileFields.Length, global::System.StringComparer.OrdinalIgnoreCase);");
        builder.AppendLine("            for (int i = 0; i < fileFields.Length; i++)");
        builder.AppendLine("                byName[fileFields[i].Path.ToString()] = fileFields[i];");
        builder.AppendLine("        }");
        builder.AppendLine("        return byName.TryGetValue(expectedPath, out var matched) ? matched : expected;");
        builder.AppendLine("    }");
    }

    private static void EmitBuildFormatOptions(StringBuilder builder)
    {
        builder.AppendLine("    private static global::Parquet.ParquetOptions BuildFormatOptions(");
        builder.AppendLine("        global::Parquet.SourceGenerator.ParquetSerializerOptions options)");
        builder.AppendLine("    {");
        builder.AppendLine("        var opts = new global::Parquet.ParquetOptions();");
        builder.AppendLine("        return opts;");
        builder.AppendLine("    }");
    }

    private static string GetArrayTypeName(PropertyModel prop)
    {
        if (prop.Kind == PropertyKind.Enum)
        {
            return prop.EnumUnderlyingTypeName ?? "int";
        }
        return prop.TypeName;
    }

    private static string BoolLiteral(bool val)
    {
        return val ? "true" : "false";
    }
}
